# 第 20 章驱动脚本：cd examples/20_dates && mix run --no-compile run.exs
:io.setopts(:standard_io, encoding: :utf8)

alias Ex20Dates

IO.puts("==== 20 日期与时间：四类结构、日历算术、区间、Unix、固定偏移、时区坑、比较 ====")

# ------------------------------------------------------------
# 1. 四个字面量与字段拆解
# ------------------------------------------------------------
IO.puts("\n-- 1. ~D/~T/~N/~U 是不同类型；字段显式可读 --")
IO.puts("  date_info => #{inspect(Ex20Dates.date_info(~D[2026-09-21]))}")
IO.puts("  time_info => #{inspect(Ex20Dates.time_info(~T[12:34:56.789]))}")
IO.puts("  无时区时刻 => #{inspect(~N[2026-09-21 08:00:00])}")

# ------------------------------------------------------------
# 2. 日期算术；月末按日历推进
# ------------------------------------------------------------
IO.puts("\n-- 2. add/diff 按日历走，月末不溢出 --")
IO.puts("  加 10 天 => #{Ex20Dates.shift_days(~D[2026-09-21], 10)}")
IO.puts("  相差 => #{Ex20Dates.days_between(~D[2026-10-01], ~D[2026-09-21])}")
IO.puts("  1-31 +1 => #{Ex20Dates.shift_days(~D[2026-01-31], 1)}")

# ------------------------------------------------------------
# 3. Date.range 闭区间，工作日计数
# ------------------------------------------------------------
IO.puts("\n-- 3. Date.range 两端包含；枚举计数 --")
IO.puts("  9 月工作日 => #{Ex20Dates.workdays(~D[2026-09-01], ~D[2026-09-30])}")

# ------------------------------------------------------------
# 4. 时刻算术与钟点滚动
# ------------------------------------------------------------
IO.puts("\n-- 4. NaiveDateTime 秒级 add/diff；Time 跨午夜取模 --")
IO.puts("  +3661 秒 => #{Ex20Dates.add_seconds(~N[2026-09-21 08:00:00], 3661)}")
IO.puts("  相差秒 => #{Ex20Dates.seconds_between(~N[2026-09-21 10:00:00], ~N[2026-09-21 08:00:00])}")
IO.puts("  23 点 +2 小时 => #{Ex20Dates.roll_hours(~T[23:00:00], 7200)}")

# ------------------------------------------------------------
# 5. Unix 互转与固定偏移
# ------------------------------------------------------------
IO.puts("\n-- 5. 与 Unix 整数互转；固定偏移=先减偏移再转 UTC --")
IO.puts("  epoch 0 => #{Ex20Dates.unix_epoch(0)}")
IO.puts("  UTC->unix => #{Ex20Dates.to_unix(~U[2026-09-21 00:00:00Z])}")
IO.puts("  北京 08:00(+8) 的 unix => #{Ex20Dates.wall_to_unix(~N[2026-09-21 08:00:00], 28800)}")

# ------------------------------------------------------------
# 6. 命名时区：零依赖全部失败
# ------------------------------------------------------------
IO.puts("\n-- 6. 未装时区数据库：命名时区（含 Etc/GMT±n）全返回 error tag --")
IO.puts("  Asia/Shanghai => #{inspect(Ex20Dates.shift_error("Asia/Shanghai"))}")

IO.puts(
  "  new 命名时区 => #{inspect(Ex20Dates.new_local(~D[2026-09-21], ~T[08:00:00], "Asia/Shanghai"))}"
)

IO.puts(
  "  new Etc/UTC => #{inspect(Ex20Dates.new_local(~D[2026-09-21], ~T[08:00:00], "Etc/UTC"))}"
)

# ------------------------------------------------------------
# 7. 比较：同类三态，跨类 tag
# ------------------------------------------------------------
IO.puts("\n-- 7. 同类型比较三态；跨类型不可比（tag 隔离，不让它崩） --")
IO.puts("  日期比较 => #{Ex20Dates.safe_compare(~D[2026-09-21], ~D[2026-09-20])}")
IO.puts("  跨类型 => #{inspect(Ex20Dates.safe_compare(~D[2026-09-21], ~T[12:00:00]))}")

IO.puts("""
-- 日期时间要点 --
  Date/Time/NaiveDateTime/DateTime 是四种类型，按「有无时刻、有无时区」选
  算术分两层：日历算术（add 天）与时刻算术（add 秒），别用错函数
  Date.range 是闭区间可枚举；跨类型比较前先确认类型一致
  存储/传输用 Unix 整数或 ~U；零依赖只有 UTC
  固定偏移：墙钟存 NaiveDateTime + 显式偏移整数，换算先减偏移
  命名时区（DST 规则）需要 tzdata 等时区数据库依赖
  确定性程序里不打印「今天/现在」——墙钟结果随运行时刻变化
""")

IO.puts("==== 20 结束 ====")
