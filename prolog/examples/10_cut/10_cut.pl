%% ============================================================================
%%  10_cut.pl —— 剪枝（cut）
%%
%%  !/0 是 Prolog 里唯一「破坏逻辑纯洁性」的控制结构：它砍掉选择点。
%%  砍掉之后回溯就回不来了 —— 也就是说 ! 不只是优化，它可能改变解集。
%%
%%  两种用法（Green/Red cut 的经典划分）：
%%    绿色剪枝：只删掉「本来也不会产生别的解」的选择点，
%%              程序语义不变，纯粹提速、省内存。
%%    红色剪枝：删掉「本来会产生别的解」的选择点，
%%              语义被改变了，必须靠注释说明为什么安全。
%%
%%  黄金准则：每个 ! 后面都补一句注释，写清「砍掉了什么、为什么可以砍」。
%% ============================================================================

:- set_prolog_flag(double_quotes, codes).

say(S) :- format("~s~n", [S]).

%% ---------------------------------------------------------------------------
%%  一、没有 ! 的麻烦：多余的解
%% ---------------------------------------------------------------------------
%% 两个子句都「乐于」匹配，回溯时会给出两个答案 —— 但最大值只有一个。
max_bad(X, Y, X) :- X >= Y.
max_bad(_X, Y, Y).

%% 加一个 ! 就定死了：第一个子句一旦命中，不再考虑第二个。
max_ok(X, Y, X) :- X >= Y, !.
max_ok(_X, Y, Y).

demo_extra_solutions :-
    say("---- 1. 没有 ! 会产生多余解 ----"),
    findall(M, max_bad(3, 1, M), L1),
    format("  findall(M, max_bad(3,1,M), L)  L = ~w（3 和 1 都在）~n", [L1]),
    findall(M2, max_ok(3, 1, M2), L2),
    format("  换成 max_ok                     L = ~w~n", [L2]),
    say("  语句层面 max_bad 的第二个解「1」是错的，"),
    say("  但 max_bad(1,3,M) 又是对的 —— 它只是「有时」错，最难查。"),

    % ! 顺手砍掉了「还有别的选择点」这个事实
    (   max_ok(3, 1, _M3)
    ->  say("  max_ok(3,1,_) 跑完就不再留选择点（! 已经砍掉了）")
    ;   say("  max_ok(3,1,_) 失败")
    ).

%% ---------------------------------------------------------------------------
%%  二、红色剪枝：语义真的变了
%% ---------------------------------------------------------------------------
%% 「第一个偶数」在逻辑上没有唯一性，! 强行让它唯一 —— 属于红剪枝。
first_even(L, X) :-
    member(X, L),
    0 =:= X mod 2,
    !.                      % 红剪枝：我们就是要第一个，后面的偶数不要

%% 等价的、把意图写在脸上的写法：once/1
first_even_alt(L, X) :-
    once(( member(X, L), 0 =:= X mod 2 )).

demo_red_cut :-
    say("---- 2. 红色剪枝：剪切改变了语义 ----"),
    first_even([1, 3, 4, 6, 8], E1),
    format("  first_even([1,3,4,6,8])    = ~w~n", [E1]),
    first_even_alt([1, 3, 4, 6, 8], E2),
    format("  first_even_alt（once 版）  = ~w~n", [E2]),
    say("  如果不加 ! 也不加 once，收集到的会是全部偶数："),
    findall(E3, ( member(E3, [1, 3, 4, 6, 8]), 0 =:= E3 mod 2 ), Evens),
    format("    ~w~n", [Evens]),
    say("  所以 first_even 的 ! 是必须留下的红剪枝，但它依赖调用者对"),
    say("  member 顺序的信任，文档里必须写明。"),
    say("  经验：能写 once/1 就别写裸 !，意图更清楚、更好维护。").

%% ---------------------------------------------------------------------------
%%  三、分号 ; 与箭头 -> 、软箭头 *->
%% ---------------------------------------------------------------------------
%% (->)/2 的语义 = (Cond, !, Then ; Else)：条件只取第一个解
%% (;)/2  不带 -> 时是真正的逻辑或，两边都能回溯出解
%% (*->)/2 软剪枝：条件可以继续回溯，但 else 分支不参与
demo_ite :-
    say("---- 3. ; 与 -> 的区别 ----"),

    findall(R, ( member(N, [1, 2, 3]),
                 ( N > 1, R = gt ; R = le ) ), Rs),
    length(Rs, N1),
    format("  (N>1, R=gt ; R=le)   共 ~w 个解：~w~n", [N1, Rs]),

    findall(R2, ( member(N2, [1, 2, 3]),
                  ( N2 > 1 -> R2 = gt ; R2 = le ) ), Rs2),
    length(Rs2, N2),
    format("  (N>1 -> R=gt ; R=le) 共 ~w 个解：~w~n", [N2, Rs2]),

    findall(R3, ( member(N3, [1, 2, 3]),
                  ( N3 > 1 *-> R3 = gt ; R3 = le ) ), Rs3),
    length(Rs3, N3),
    format("  (N>1 *-> R=gt ; R=le) 共 ~w 个解：~w~n", [N3, Rs3]),

    say("  N=2 时第一种写法给出了 gt 与 le 两个解 —— 这正是"),
    say("  「分号只是或」与「箭头才会剪枝」的差别。"),
    say("  *-> 与 -> 在条件只有一个解时看不出差别；"),
    say("  条件本身能回溯出多解时（例如条件就是 member/2）才分道扬镳。").

%% ---------------------------------------------------------------------------
%%  四、\+/1 与 once/1 都是 ! 的封装
%% ---------------------------------------------------------------------------
%% \+ G 在 ISO 标准里等价于 (G, !, fail ; true)
my_not(G) :- call(G), !, fail.
my_not(_).

%% once/1 在 ISO 标准里等价于 (G, !)
my_once(G) :- call(G), !.

demo_wrappers :-
    say("---- 4. \\+ 与 once 都是 ! 的封装 ----"),
    (   my_not(member(9, [1, 2, 3]))
    ->  say("  my_not(member(9,[1,2,3]))  成立")
    ;   say("  my_not(member(9,[1,2,3]))  不成立")
    ),
    findall(X, my_once(member(X, [a, b, c])), L1),
    format("  findall(X, my_once(member(X,[a,b,c])), L)  L = ~w~n", [L1]),
    say("  once = 只取第一个解；\\+ = 取第一个解再取反。"),
    say("  两者都掐掉了不确定性，所以适合放在需要判定的位置。"),

    % 经典陷阱：\+ 里带未绑定变量，绑定会被丢掉
    (   my_not(member(_X2, [a, b]))
    ->  say("  my_not(member(X,[a,b]))    成立（这里不该出现）")
    ;   say("  my_not(member(X,[a,b]))    不成立，而且 X 没被绑定")
    ).

%% ---------------------------------------------------------------------------
%%  五、! 与「没有答案」的表达
%% ---------------------------------------------------------------------------
%% 从列表里找第一个满足条件的元素，找到就停
find_first(L, P, X) :-
    member(X, L),
    call(P, X),
    !.                      % 找到就砍掉 member 的其余选择点

bigger_than_6(X) :- X > 6.

demo_no_answer :-
    say("---- 5. ! 与「没有答案」的表达 ----"),
    find_first([1, 3, 5, 8, 9], bigger_than_6, X),
    format("  find_first([1,3,5,8,9], >6)  = ~w~n", [X]),
    (   find_first([1, 2, 3], bigger_than_6, _X2)
    ->  say("  在不含 >6 的列表里：找到了")
    ;   say("  在不含 >6 的列表里：目标直接失败")
    ),
    say("  Prolog 用「失败」表示「没有」，不返回 null 也不抛异常 ——"),
    say("  这是从命令式／函数式过来的第二大坎（第一坎是第 05 章的合一）。"),
    say("  想显式表达「可能没有」，就自己包一层：返回 none / some(X)（第 20 章）。").

%% ---------------------------------------------------------------------------
%%  入口
%% ---------------------------------------------------------------------------
main :-
    (   catch(run, E, (format(user_error, "*** 异常: ~q~n", [E]), halt(1)))
    ->  halt(0)
    ;   format(user_error, "*** run/0 失败~n", []),
        halt(1)
    ).

run :-
    format("==== 10 开始 ====~n", []),
    say("!/0 砍掉选择点 —— 它既是优化，也可能改变语义，用前先想清楚。"),
    say(""),

    demo_extra_solutions, say(""),
    demo_red_cut,         say(""),
    demo_ite,             say(""),
    demo_wrappers,        say(""),
    demo_no_answer,       say(""),

    format("==== 10 结束 ====~n", []).
