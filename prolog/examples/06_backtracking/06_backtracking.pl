%% ============================================================================
%%  06_backtracking.pl —— 回溯：Prolog 的「重新来过」
%%
%%  一个目标可能有多条成功路径；Prolog 先走第一条，如果后面失败了，
%%  它会退回到最近一个「还有别的选择」的地方换一条路。这就是回溯。
%%
%%  本章不用任何高级工具，只用 member/2、findall/3、;/2、->/2 和几个
%%  带副作用的谓词，把「证明树怎么走」直接打出来。
%% ============================================================================

:- set_prolog_flag(double_quotes, codes).

say(S) :- format("~s~n", [S]).

%% ---------------------------------------------------------------------------
%%  一、最直观的回溯：一个带打印的分支谓词
%%  每次尝试都留一行痕迹，就能看见引擎到底试了几次。
%% ---------------------------------------------------------------------------
pick(X) :-
    member(X, [a, b, c]),
    format("  尝试 ~w -> ", [X]),
    (   X == b
    ->  format("接受~n", [])
    ;   format("拒绝，回溯~n", []),
        fail
    ).

demo_trace :-
    say("---- 1. 回溯长什么样 ----"),
    findall(X, pick(X), L),
    format("  最终成功解 = ~w~n", [L]),
    say("  可以看到：a 被拒后回退到 member/2 的第二个解，而不是从头再来。").

%% ---------------------------------------------------------------------------
%%  二、成功之后不回头：确定性谓词
%% ---------------------------------------------------------------------------
%%  member(a, [a, a]) 有两条成功路径，但 Prolog 只报第一条，
%%  除非你主动要求更多解。用 findall 就能看出「一共有几个解」。
demo_determinism :-
    say("---- 2. 一个目标可以有多个解，也可以被「定死」----"),
    findall(_X1, member(a, [a, a, a]), L1),
    length(L1, N1),
    format("  member(a,[a,a,a]) 一共有 ~w 个解~n", [N1]),
    findall(_X2, memberchk(a, [a, a, a]), L2),
    length(L2, N2),
    format("  换成 memberchk 只有 ~w 个（它只认第一条）~n", [N2]).

%% ---------------------------------------------------------------------------
%%  三、逗号是「并且」，分号是「或者」，-> 是「那么」
%% ---------------------------------------------------------------------------
demo_connectives :-
    say("---- 3. 控制结构：,  ;  ->  *->  ----"),

    % (,)/2 —— 合取：从左到右，前一个成功才做后一个
    (   member(2, [1, 2, 3]),
        member(3, [1, 2, 3])
    ->  say("  (member(2..), member(3..))  成功")
    ;   say("  (member(2..), member(3..))  失败")
    ),

    % (;)/2 —— 析取：左边失败就试右边
    findall(X, ( X = 1 ; X = 2 ), L3),
    format("  (X=1 ; X=2) 的解除非 ~w~n", [L3]),

    % (->)/2 —— if-then-else：条件成功一次，就砍掉条件上的其余选择点
    findall(Y, ( member(Y, [1, 2, 3]), ( Y > 1 -> true ; fail ) ), L4),
    format("  member(Y,[1,2,3]) 且 Y>1 的解 = ~w~n", [L4]),

    % (*->)/2 —— 软切：条件可以继续回溯
    findall(Z, ( member(Z, [1, 2, 3]), ( Z > 1 *-> true ; fail ) ), L5),
    format("  用 *-> 的同一查询 = ~w（这里是相同结果，差别见第 10 章）~n", [L5]),

    % \+/2 —— 否定作为失败
    (   \+ member(9, [1, 2, 3])
    ->  say("  \\+ member(9,[1,2,3])       成功")
    ;   say("  \\+ member(9,[1,2,3])       失败")
    ).

%% ---------------------------------------------------------------------------
%%  四、循环：Prolog 没有 for，用递归和「失败驱动的循环」
%% ---------------------------------------------------------------------------
countdown(N) :-
    N > 0,
    format("  ~w ...~n", [N]),
    N1 is N - 1,
    countdown(N1).
countdown(0) :-
    say("  发射！").

%% repeat/0 永远成功，专门用来制造选择点；配合 ! 就是「一直试到成功」。
%% 注意：! 必须在子句里「切在 repeat 之后」，否则循环不会停。
search(Guess) :-
    repeat,
    next_guess(Guess),
    format("  试 ~w ... ", [Guess]),
    (   acceptable(Guess)
    ->  format("可用！~n", []),
        !
    ;   format("不行~n", []),
        fail
    ).

next_guess(X) :- member(X, [1, 3, 7, 8]).
acceptable(X) :- X > 5.

demo_repeat :-
    say("---- 4. 递归与「失败驱动」循环 ----"),
    countdown(3),
    say("  上面是递归；下面用 repeat/0 + ! 一路试到成功："),
    search(G),
    format("  找到的第一个可用值 = ~w~n", [G]),
    say("  这是 Prolog 版的 while(true)，! 负责跳出。").

counter(N) :-
    N =< 5,
    format("  计数第 ~w 次~n", [N]),
    N1 is N + 1,
    counter(N1).
counter(_).

%% ---------------------------------------------------------------------------
%%  五、findall：把「所有解」变成「一个列表」
%%  这是把回溯变成数据的标准手段，之后就能像普通列表一样处理。
%% ---------------------------------------------------------------------------
demo_findall :-
    say("---- 5. findall/3：回溯 → 列表 ----"),
    findall(N, between(1, 5, N), L1),
    format("  between(1,5,N) 的全部解   = ~w~n", [L1]),

    % 模板可以不是变量：这里收集平方
    findall(N2 * N2, between(1, 5, N2), L2),
    format("  收集 N*N                  = ~w~n", [L2]),

    % findall 内部失败不影响外层：收集到空表，目标仍然成功
    findall(_N3, member(9, [1, 2]), L3),
    format("  无解时收集到             = ~w（findall 本身成功）~n", [L3]),
    say("  对比：bagof/3 在无解时会失败，setof/3 还会排序去重（第 13 章）。").

%% ---------------------------------------------------------------------------
%%  入口
%% ---------------------------------------------------------------------------
main :-
    (   catch(run, E, (format(user_error, "*** 异常: ~q~n", [E]), halt(1)))
    ->  halt(0)
    ;   format(user_error, "*** run/0 失败~n", []),
        halt(1)
    ).

run :-
    format("==== 06 开始 ====~n", []),
    say("Prolog 的「控制流」就是回溯本身，没有任何循环语句。"),
    say(""),

    demo_trace,       say(""),
    demo_determinism, say(""),
    demo_connectives, say(""),
    demo_repeat,      say(""),
    demo_findall,     say(""),

    format("==== 06 结束 ====~n", []).
