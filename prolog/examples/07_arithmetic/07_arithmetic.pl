%% ============================================================================
%%  07_arithmetic.pl —— 算术与数值
%%
%%  Prolog 的算术有几个反直觉的地方：
%%    - 算术表达式是「项」，不是值：1+2 是一个复合项 +(1,2)
%%    - 必须用 is/2 「求值」才会算成 3
%%    - =/2 只做合一，不计算：X = 1+2 把 X 绑成项 1+2，不是 3
%%    - 比较用 =:=  =\\=  <  >  =<  >=（算术比较）
%%      别用 ==/2 与 @<(标准项序，第 04 章)
%%
%%  本章只用两套引擎必然一致的运算与打印方式，浮点打印的坑单独一节讲。
%% ============================================================================

:- set_prolog_flag(double_quotes, codes).

say(S) :- format("~s~n", [S]).

%% 「算一下再打印」的两个助手：整数用 ~w，浮点用 ~3f。
ival(Label, Value) :- format("  ~s = ~w~n", [Label, Value]).
fval(Label, Value) :- format("  ~s = ~3f~n", [Label, Value]).

%% ---------------------------------------------------------------------------
%%  一、is/2：求值
%% ---------------------------------------------------------------------------
demo_is :-
    say("---- 1. is/2 求值 ----"),
    E = 1 + 2,
    format("  X = 1+2   之后 X 是  ~w（还是个项）~n", [E]),
    X is 1 + 2,
    format("  X is 1+2  之后 X 是  ~w~n", [X]),
    V1 is 3 + 4 * 5,
    ival("3 + 4 * 5  ", V1),
    V2 is (3 + 4) * 5,
    ival("(3 + 4) * 5", V2),
    say("  括号改变的是项的结构，进而改变求值结果。"),
    say("  两套引擎的运算符优先级与结合性完全一致，可以放心依赖括号。"),
    (   catch(_V4 is _A5 + 1, _, fail)
    ->  say("  is 右边有未绑定变量时：异常没被 catch 到")
    ;   say("  is 右边有未绑定变量时：抛 instantiation_error（两边一致）")
    ),
    say("  所以 is/2 是「计算式」而不是「等式」，不能反着解方程 ——"),
    say("  要做反解就用关系式谓词（succ/2、between/3、length/2，见第 6 节）。").

%% ---------------------------------------------------------------------------
%%  二、整数运算
%% ---------------------------------------------------------------------------
demo_int :-
    say("---- 2. 整数运算 ----"),
    I1 is 7 + 2,     ival("7 + 2    ", I1),
    I2 is 7 - 2,     ival("7 - 2    ", I2),
    I3 is 7 * 2,     ival("7 * 2    ", I3),
    I4 is 7 // 2,    ival("7 // 2   ", I4),
    I5 is 7 div 2,   ival("7 div 2  ", I5),
    I6 is -7 // 2,   ival("-7 // 2  ", I6),
    I7 is -7 div 2,  ival("-7 div 2 ", I7),
    say("  // 向零截断，div 向下取整 —— 负数时才看得出区别。"),
    I8 is 7 rem 2,   ival("7 rem 2  ", I8),
    I9 is 7 mod 2,   ival("7 mod 2  ", I9),
    I10 is -7 rem 2, ival("-7 rem 2 ", I10),
    I11 is -7 mod 2, ival("-7 mod 2 ", I11),
    say("  rem 的符号跟被除数，mod 的符号跟除数。"),
    I12 is abs(-7),  ival("abs(-7)  ", I12),
    I13 is sign(-7), ival("sign(-7) ", I13),
    I14 is min(3, 9), ival("min(3,9) ", I14),
    I15 is max(3, 9), ival("max(3,9) ", I15),
    I16 is 2 ^ 10,   ival("2 ^ 10   ", I16),
    I17 is gcd(12, 18), ival("gcd(12,18)", I17),
    say("  整数是无界的（不像 C 会溢出）——这是 ISO 要求，两套引擎都满足。").

%% ---------------------------------------------------------------------------
%%  三、位运算
%% ---------------------------------------------------------------------------
demo_bits :-
    say("---- 3. 位运算 ----"),
    B1 is 12 /\ 10, ival("12 /\\ 10", B1),
    B2 is 12 \/ 10, ival("12 \\/ 10", B2),
    B3 is \ 12,     ival("\\ 12  ", B3),
    B4 is 1 << 4,   ival("1 << 4 ", B4),
    B5 is 16 >> 2,  ival("16 >> 2", B5),
    say("  没有通用的异或运算符：X = (A \\/ B) /\\ \\ (A /\\ B) 才是可移植写法。"),
    say("  （SWI 额外提供 xor/2，GNU Prolog 不认，所以本教程不用。）").

%% ---------------------------------------------------------------------------
%%  四、浮点运算与「怎么打印浮点」这个大坑
%% ---------------------------------------------------------------------------
demo_float :-
    say("---- 4. 浮点运算 ----"),
    F1 is 7 / 2,     fval("7 / 2", F1),
    F2 is sqrt(2),   fval("sqrt(2)", F2),
    F3 is sqrt(16),  fval("sqrt(16)", F3),
    F4 is floor(3.7),   fval("floor(3.7)", F4),
    F5 is ceiling(3.2), fval("ceiling(3.2)", F5),
    F6 is round(3.7),   fval("round(3.7)", F6),
    F7 is truncate(3.7), fval("truncate(3.7)", F7),
    F8 is float_integer_part(3.7),     fval("float_integer_part(3.7)", F8),
    F9 is float_fractional_part(3.75), fval("float_fractional_part(3.75)", F9),
    F10 is float(3),  fval("float(3)", F10),
    F11 is exp(0),    fval("exp(0)", F11),
    F12 is log(1),    fval("log(1)", F12),
    F13 is sin(0),    fval("sin(0)", F13),
    F14 is cos(0),    fval("cos(0)", F14),
    F15 is pi,        fval("pi", F15),

    say(""),
    say("  浮点打印有三个必须知道的事实："),
    say("    1. 二进制浮点不能精确表示 0.1 / 3.14 这类十进制小数；"),
    say("    2. ~w 打浮点：SWI 打「能读回来的最短写法」，GNU 打 17 位有效数字。"),
    say("       所以用 ~w 打 3.14 会得到 3.14 与 3.1400000000000001 —— 不一致；"),
    say("    3. 定点 ~2f / ~3f 与科学计数 ~e / ~g 两边算法一致，可以放心用。"),
    say("  本教程的约定：浮点一律用 ~2f / ~3f / ~e / ~g 打印。"),
    say("  x.5、x.25 这类二进制可精确表示的浮点，用 ~w 才安全。"),
    format("  例如 ~w 与 ~w~n", [0.25, 0.75]),
    say(""),
    say("  还有一条更隐蔽的坑：/ 的结果类型两边不一致。"),
    say("    7 / 2 = 3.5  两边都是浮点（没问题）"),
    say("    4 / 2 = ?    SWI 给整数 2，GNU 给浮点 2.0 ——"),
    say("  所以可移植代码里「整除」一律写 //，别指望 / 帮你约分。").

%% ---------------------------------------------------------------------------
%%  五、算术比较
%% ---------------------------------------------------------------------------
cmp(Label, Goal) :-
    format("  ~s", [Label]),
    (   call(Goal)
    ->  say("成立")
    ;   say("不成立")
    ).

demo_cmp :-
    say("---- 5. 算术比较 ----"),
    cmp("2 =:= 2.0   ", 2 =:= 2.0),
    cmp("2 =\\= 3     ", 2 =\= 3),
    cmp("2 <  3      ", 2 < 3),
    cmp("2 >  3      ", 2 > 3),
    cmp("2 =< 2      ", 2 =< 2),
    cmp("2 >= 3      ", 2 >= 3),
    cmp("2 @< 2.0    ", 2 @< 2.0),
    say("  最后一条是标准项序 @</2：整数排在浮点前面，所以 2 @< 2.0 成立；"),
    say("  而 2 =:= 2.0 也成立 —— 两套「序」不能混用。"),
    say("  更要命的是整数与浮点混排时，两套引擎的标准项序不一致，"),
    say("  所以 sort/msort 里绝不要混整数和浮点（第 23 章）。").

%% ---------------------------------------------------------------------------
%%  六、关系式算术：succ/2、between/3、length/2
%% ---------------------------------------------------------------------------
demo_rels :-
    say("---- 6. 关系式算术：不用 is 也能算 ----"),
    succ(4, S1),
    format("  succ(4, X)          X = ~w~n", [S1]),
    succ(S2, 5),
    format("  succ(X, 5)          X = ~w~n", [S2]),

    findall(N, between(1, 5, N), L1),
    format("  between(1, 5, X)    ~w~n", [L1]),
    % between/4（带步长）两套引擎都没有，自己叠加条件即可
    findall(N2, ( between(1, 9, N2), 0 =:= N2 mod 3 ), L2),
    format("  between(1, 9, X) 且 X mod 3 = 0：~w~n", [L2]),

    length([a, b, c], N3),
    format("  length([a,b,c], N)  N = ~w~n", [N3]),
    length(L3, 3),
    numbervars(L3, 0, _),
    format("  length(L, 3)        L = ~w~n", [L3]),
    say("  一个谓词多种用法，是 Prolog 区别于函数式与命令式的核心特征："),
    say("  它描述的是「关系」，不是「函数」。").

%% ---------------------------------------------------------------------------
%%  入口
%% ---------------------------------------------------------------------------
main :-
    (   catch(run, E, (format(user_error, "*** 异常: ~q~n", [E]), halt(1)))
    ->  halt(0)
    ;   format(user_error, "*** run/0 失败~n", []),
        halt(1)
    ).

run :-
    format("==== 07 开始 ====~n", []),
    say("算术表达式在 Prolog 里是项，is/2 才是求值开关。"),
    say(""),

    demo_is,    say(""),
    demo_int,   say(""),
    demo_bits,  say(""),
    demo_float, say(""),
    demo_cmp,   say(""),
    demo_rels,  say(""),

    format("==== 07 结束 ====~n", []).
