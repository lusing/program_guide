%% ============================================================================
%%  02_hello.pl —— 第一个程序：三条运行通道与输出约定
%%
%%  这是全教程的模板文件，后面每个示例都照这个骨架写：
%%    1. 顶部 set_prolog_flag 统一双引号含义（否则两套引擎行为分叉）
%%    2. main/0 是入口 —— Prolog 本身没有 main 的概念，脚本化运行才需要它
%%    3. run/0 干活，只打印「两套引擎必然一致」的内容
%%    4. 输出区间用 ==== NN 开始 ==== / ==== NN 结束 ==== 圈起来
%%    5. main/0 结尾必须 halt —— 否则失败时会掉进交互式 toplevel 卡住
%%
%%  三条运行通道（run-all.sh 每条都跑一遍）：
%%    swipl   -Dencoding=utf8 -q -f 02_hello.pl -g main -t halt
%%    gprolog --consult-file 02_hello.pl --entry-goal main
%%    gplc    编译成本地可执行文件后运行（无运行时依赖）
%% ============================================================================

% 双引号统一按「字符码列表」解释。SWI 默认是 string 对象，GNU 默认是 codes，
% 不写这一行后面所有涉及 "abc" 的代码两边行为都不一样（详见第 15 章）。
:- set_prolog_flag(double_quotes, codes).

%% ---------------------------------------------------------------------------
%%  say/1：打一行常量文字。
%%  两套引擎的 format/2 都能吃空参数列表，但把常量行交给一个封装，
%%  能把「格式串里的 ~ 忘了转义」这类事故挡在外面。
%%  ~s 按字符码原样输出，中英文都不会被加引号 —— 这是唯一的稳妥通道。
%% ---------------------------------------------------------------------------
say(S) :- format("~s~n", [S]).

%% ---------------------------------------------------------------------------
%%  一个事实就是一个「值」
%% ---------------------------------------------------------------------------
program_name('Prolog 教程示例 02').

%% ---------------------------------------------------------------------------
%%  输出三件套：write / writeq / format
%% ---------------------------------------------------------------------------
demo_output :-
    say("---- 输出三件套 ----"),

    % write/1：原样打，不加引号。原子带空格时看不出边界，是坑。
    format("write/1   : ~w~n", [prolog]),
    format("write/1   : ~w~n", [[a, b]]),

    % writeq/1：必要时加引号，程序里「回显给程序员看」用它。
    format("writeq/1  : ~q~n", ['hello world']),
    format("writeq/1  : ~q~n", [[a, 1]]),

    % format/2：唯一能在两套引擎上稳定控制排版与数值格式的手段。
    format("format/2  : ~w / ~q / ~a~n", [plain, 'a b', plain]),

    % 换行：nl/0 与格式串里的 ~n 等价，但 nl 还能指定流（第 14 章）。
    say("nl/0 与 ~n 等价").

%% ---------------------------------------------------------------------------
%%  format 的常用说明符：下面这些在两套引擎上输出逐字节相同
%%  写法约定：格式串里除了真正的说明符，字面文字里不要出现 ~ ，
%%  否则会被当成说明符，去实参列表里找参数（找不到就报 not enough arguments）。
%% ---------------------------------------------------------------------------
demo_format :-
    say("---- format 说明符 ----"),
    spec("w  通用",     "~w~n",   [[1, a, f(x)]]),
    spec("q  加引号",   "~q~n",   ['a b']),
    spec("a  原子",     "~a~n",   [plain]),
    spec("d  十进制",   "~d~n",   [255]),
    spec("c  字符",     "~c~n",   [65]),
    spec("2f 定点两位", "~2f~n",  [3.14159]),
    spec("3f 定点三位", "~3f~n",  [3.14159]),
    spec("e  科学计数", "~e~n",   [31415.9]),
    spec("r  指定进制", "~r~n",   [10]),
    % 一行里混排：实参按顺序喂给各说明符
    format("  混排 : ~w 有 ~w 个孩子，第 ~w 个叫 ~w~n", [bob, 2, 1, ann]).

% 标签用 ~s（字符码原样输出），别用 ~w —— 双引号串是字符码列表，
% ~w 会把整串数字打出来。
spec(Label, Fmt, Args) :-
    format("  ~s : ", [Label]),
    format(Fmt, Args).

%% ---------------------------------------------------------------------------
%%  中文输出：字符级的操作要小心（第 15 章细讲），只管显示是安全的
%% ---------------------------------------------------------------------------
demo_utf8 :-
    say("---- 中文输出 ----"),
    say("  UTF-8 直出: 事实 → 规则 → 查询"),
    say("  用 ~s 说明符打中文字符码列表: "),
    format("~s~n", ["      逻辑编程"]),
    say("  用 ~w 说明符打中文原子: "),
    format("~w~n", ['      逻辑编程']),
    % 长度 / 字符码这类「按字符数」的操作，中英文结论完全不同 ——
    % SWI 按 Unicode 码点算，GNU Prolog 按 UTF-8 字节算。
    format("  atom_length(ascii)    : ~w~n", [5]),
    atom_length(hello, N),
    format("  atom_length('hello')  : ~w~n", [N]),
    say("  中文的 atom_length 两边不同（4 vs 12），本教程一律不做这种操作").

%% ---------------------------------------------------------------------------
%%  命令行参数：两套引擎对 argv 的填充方式不同，只用它做「可读性」探测
%% ---------------------------------------------------------------------------
demo_argv :-
    say("---- 命令行参数 ----"),
    (   catch(current_prolog_flag(argv, _), _, fail)
    ->  say("  argv 标志可读: 是")
    ;   say("  argv 标志可读: 否")
    ),
    say("  但 argv 的内容与长度两边不同（GNU 会把 --consult-file 之类算进去），"),
    say("  可移植代码不要依赖 argv[0]；真要参数就走环境变量或固定文件名。").

%% ---------------------------------------------------------------------------
%%  部署与退出码约定：CI 直接读退出码
%% ---------------------------------------------------------------------------
demo_deploy :-
    say("---- 部署与退出码 ----"),
    say("  开发期解释执行："),
    say("    swipl   -q -f prog.pl -g main -t halt"),
    say("    gprolog --consult-file prog.pl --entry-goal main"),
    say("  发布期编译："),
    say("    swipl -o prog -c prog.pl    （源文件要有 :- initialization(main, main). ）"),
    say("    gplc  entry.pl -o prog      （entry.pl 首行 :- initialization(main). ）"),
    say("  约定：run/0 走到底 -> halt(0)；出岔子 -> 原因写 stderr 并 halt(1)。").

%% ---------------------------------------------------------------------------
%%  入口
%% ---------------------------------------------------------------------------
main :-
    (   catch(run, E, (format(user_error, "*** 异常: ~q~n", [E]), halt(1)))
    ->  halt(0)
    ;   format(user_error, "*** run/0 失败~n", []),
        halt(1)
    ).

run :-
    format("==== 02 开始 ====~n", []),
    say("Prolog 程序没有 main，本教程用 main/0 把「跑一遍」脚本化。"),
    program_name(Name),
    format("本示例：~a~n", [Name]),
    say(""),

    demo_output,  say(""),
    demo_format,  say(""),
    demo_utf8,    say(""),
    demo_argv,    say(""),
    demo_deploy,  say(""),

    format("==== 02 结束 ====~n", []).
