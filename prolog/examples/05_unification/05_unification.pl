%% ============================================================================
%%  05_unification.pl —— 合一：Prolog 唯一的「赋值」机制
%%
%%  命令式语言用 x = 3 把值塞进盒子；Prolog 的 =/2 是「让两边变成同一个项」。
%%  这一条差别衍生出整套语言：
%%    - 没有赋值语句，只有绑定
%%    - 绑定可以做一次，也可以回溯掉（第 06 章）
%%    - 一个变量只能绑一次，绑了就不能改（要改就造新变量）
%%
%%  本章覆盖：=/2  \\=/2  ==/2  \\==/2  unify_with_occurs_check/2
%%            term_variables/2  copy_term/2  numbervars/3
%% ============================================================================

:- set_prolog_flag(double_quotes, codes).

say(S) :- format("~s~n", [S]).

%% check(+Label, :Goal) —— 跑一个目标，把「成功/失败」按统一格式打出来。
%% 用 call/1 把目标当数据传进来，这样判定逻辑只写一遍。
check(Label, Goal) :-
    format("  ~s", [Label]),
    (   call(Goal)
    ->  say("成功")
    ;   say("失败")
    ).

%% ---------------------------------------------------------------------------
%%  一、=/2：合一
%% ---------------------------------------------------------------------------
demo_unify :-
    say("---- 1. =/2 合一 ----"),

    % 变量与任何项都能合一，结果是「变量被绑定」
    X = 42,
    format("  X = 42            成功后 X = ~w~n", [X]),

    % 复合项逐层比较：名字和元数要一样，参数递归地合一
    f(A, b) = f(a, B),
    format("  f(A,b) = f(a,B)   成功后 A = ~w，B = ~w~n", [A, B]),

    % 完全相同的项：成功，但没有任何新绑定
    check("f(1,2) = f(1,2)   ", f(1, 2) = f(1, 2)),
    % 参数对不上：失败
    check("f(1,2) = f(1,3)   ", f(1, 2) = f(1, 3)),
    % 元数不同：失败（f/1 与 f/2 是两个不同的函子）
    check("f(1)   = f(1,2)   ", f(1) = f(1, 2)),
    % 不同原子：失败
    check("a = b             ", a = b),
    % 原子与数字：失败
    check("a = 1             ", a = 1),
    % 整数与浮点：ISO 规定它们不是同一个项，合一失败
    check("1 = 1.0           ", 1 = 1.0),
    % 列表就是一种复合项：'.'(H,T)
    check("[a,b] = [a|T]     ", [a, b] = [a | _T2]),
    [a, b] = [a | T3],
    format("  [a,b] = [a|T] 成功后 T 被绑成 ~w~n", [T3]).

%% ---------------------------------------------------------------------------
%%  二、==/2 与 \==/2：同一性，不建立绑定
%% ---------------------------------------------------------------------------
demo_identity :-
    say("---- 2. ==/2 同一性（只看是否已经是同一个项，不做绑定）----"),

    % 两个不同的空变量不是「同一个」，所以 == 失败而 = 成功
    check("X == Y  （都是空变量）", V1 == V2),
    check("X =  Y  （都是空变量）", V1 = V2),
    format("  V1 = V2 之后 V1 == V2 : ~w~n", [true]),
    check("V1 == V2（已合一）    ", V1 == V2),

    % 结构相同但不是一个东西：\== 成功
    check("f(1) \\== f(2)         ", f(1) \== f(2)),
    check("f(1) \\=  f(2)         ", f(1) \= f(2)),

    say("  口诀：= 会绑定，== 不绑定；\\= 问「能不能合一」，\\== 问「是不是同一个」。"),
    say("  实现细节：==/2 拿两个项的地址比，O(1)；=/2 递归走结构。").

%% ---------------------------------------------------------------------------
%%  三、\+/1：只要「能合一就失败」
%% ---------------------------------------------------------------------------
demo_not :-
    say("---- 3. \\+/1 不是什么，而是「推不出来」----"),
    check("\\+ (a = b)            ", \+ a = b),
    check("\\+ (a = a)            ", \+ a = a),
    check("\\+ member(c,[a,b])    ", \+ member(c, [a, b])),
    % \+ 的经典陷阱：目标里的变量绑定会被丢掉
    (   \+ member(_X, [a, b])
    ->  say("  \\+ member(X,[a,b]) 成功（这里不该出现）")
    ;   say("  \\+ member(X,[a,b]) 失败 —— 确实存在 X 让成员关系成立")
    ),
    % 换成「一定能推出来」的目标，\+ 才成功；但 X 不会被绑上
    (   \+ \+ member(_Y, [a, b])
    ->  say("  \\+ \\+ member(X,[a,b]) 成功，但 X 仍是空的（双重否定只回答真假）")
    ;   say("  \\+ \\+ member(X,[a,b]) 失败")
    ),
    say("  口诀：\\+ 只回答「能不能推出来」，绝不作为生成解的手段。").

%% ---------------------------------------------------------------------------
%%  四、出现检查：unify_with_occurs_check/2
%% ---------------------------------------------------------------------------
demo_occurs :-
    say("---- 4. 出现检查（occurs check）----"),
    % X = f(X) 会造出无限项。ISO 提供一个显式做检查的合一
    check("unify_with_occurs_check(X, f(X))", unify_with_occurs_check(Y1, f(Y1))),
    (   unify_with_occurs_check(Y2, f(a))
    ->  format("  unify_with_occurs_check(X, f(a))  成功后 X = ~w~n", [Y2])
    ;   say("  unify_with_occurs_check(X, f(a))  失败")
    ),
    say("  默认的 =/2 不做出现检查，Y = f(Y) 会成功并造出环状项。"),
    say("  环状项的打印方式两套引擎不同，本教程一律不打印它。"),
    say("  要可移植就别造环；需要检查时显式调用 unify_with_occurs_check/2。").

%% ---------------------------------------------------------------------------
%%  五、term_variables / copy_term / numbervars —— 操作「带变量的项」
%% ---------------------------------------------------------------------------
demo_vars :-
    say("---- 5. 拿变量、复制项、给变量编号 ----"),

    T = pair(_A, _B),
    term_variables(T, Vs),
    length(Vs, NV),
    format("  term_variables(pair(_,_)) 个数 = ~w~n", [NV]),

    % 同一个变量出现两次，只算一个
    T2 = triple(C1, _D, C1),
    term_variables(T2, Vs2),
    length(Vs2, NV2),
    format("  term_variables(triple(_,_,_)) 个数 = ~w~n", [NV2]),

    % copy_term/2：结构照抄，变量换成全新的 —— 两张互不干扰的「模板」
    copy_term(T, Copy),
    T = pair(E1, _F),
    Copy = pair(_G, _H),
    E1 = 1,

    % 打印带变量的项之前必须 numbervars/3，否则变量名是引擎内部编号，
    % 两套引擎各不相同（第 23 章会专门讲）。
    numbervars(T, 0, _),
    numbervars(Copy, 0, _),
    format("  原件第一个参数改成 1 之后：原件 = ~w~n", [T]),
    format("                             副本 = ~w~n（副本不受影响）", [Copy]),

    % numbervars/3 会把变量真的绑成 $VAR(N)，所以赋值必须放在它之前
    T4 = pair(I1, _J),
    I1 = keep_me,
    numbervars(T4, 0, _),
    format("  先给第一个参数赋值再编号  = ~w~n", [T4]).

%% ---------------------------------------------------------------------------
%%  入口
%% ---------------------------------------------------------------------------
main :-
    (   catch(run, E, (format(user_error, "*** 异常: ~q~n", [E]), halt(1)))
    ->  halt(0)
    ;   format(user_error, "*** run/0 失败~n", []),
        halt(1)
    ).

run :-
    format("==== 05 开始 ====~n", []),
    say("合一（unification）是 Prolog 唯一的「赋值」，也是它全部威力的来源。"),
    say(""),

    demo_unify,    say(""),
    demo_identity, say(""),
    demo_not,      say(""),
    demo_occurs,   say(""),
    demo_vars,     say(""),

    format("==== 05 结束 ====~n", []).
