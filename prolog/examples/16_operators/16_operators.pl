%% ============================================================================
%%  16_operators.pl —— 运算符就是语法糖
%%
%%  a + b 在 Prolog 里不是一个「运算」，它就是复合项 +(a, b)。
%%  x + 1 写成 +(x, 1) 完全可以，两者严格等价：
%%      X = 1 + 2,  X =.. L   ->  L = [+, 1, 2]
%%
%%  运算符由 op(优先级, 类型, 名字) 声明，只影响【读入时的解析】，
%%  不影响运行。一条 op/3 声明包含三个信息：
%%      优先级  1..1200，数字越大越松（越晚结合）
%%      类型    xfx / xfy / yfx（中缀）  fy / fx（前缀）  xf / yf（后缀）
%%              x 表示该侧优先级必须【严格小于】本运算符，y 表示可以相等
%%      名字    一个原子
%%
%%  注意 op/3 是全局副作用：声明之后【整个会话】都用新语法读入。
%% ============================================================================

:- set_prolog_flag(double_quotes, codes).

say(S) :- format("~s~n", [S]).

%% ---------------------------------------------------------------------------
%%  自定义运算符
%%  这三个名字在两套引擎里都没有冲突，可以安全占用。
%% ---------------------------------------------------------------------------
:- op(700, xfx, ===>).      % 非结合中缀，优先级 700
:- op(200, xfy, vv).        % 右结合中缀
:- op(200, yfx, ww).        % 左结合中缀
:- op(100, fy,  must).      % 前缀

%% ---------------------------------------------------------------------------
%%  一、运算符只是函子的糖
%% ---------------------------------------------------------------------------
demo_sugar :-
    say("---- 1. 运算符 = 函子 + 括号的省写 ----"),
    X = 1 + 2,
    X =.. L,
    format("  X = 1 + 2，X =.. L  ->  L = ~w~n", [L]),
    Y = +(1, 2),
    (   X == Y
    ->  say("  +(1,2) 与 1+2 完全同一个项（== 成立）")
    ;   say("  +(1,2) 与 1+2 不是同一个项")
    ),
    % 前缀减号也是一元函子 —— 但这里有个真坑，见下
    Z = must go,
    Z =.. L2,
    format("  Z = must go，Z =.. L  ->  L = ~w~n", [L2]),
    say("  坑：写 - 3（带空格）时，SWI 读成一元项 -(3)，GNU Prolog 读成整数 -3，"),
    say("      univ 结果一个是 [-,3]、一个是 [-3]。所以本教程一律写 -3（不留空格），"),
    say("      负数常量就写负号紧贴数字，千万别写「- 3」。"),
    say("  所以要判断「这是不是加法」，比较的是 functor，不是「运算符」。"),
    (   functor(1 + 2, F, A)
    ->  format("  functor(1+2, F, A)  ->  F = ~w，A = ~w~n", [F, A])
    ;   say("  functor 失败")
    ).

%% ---------------------------------------------------------------------------
%%  二、优先级与结合性：解析结果可以直接看
%% ---------------------------------------------------------------------------
demo_parse :-
    say("---- 2. 优先级与结合性 ----"),
    % * 的优先级比 + 高（400 < 500），所以 2*3 先结合
    T1 = 1 + 2 * 3,
    format("  1 + 2 * 3     读成 ", []),
    write_canonical(T1),
    nl,
    T2 = (1 + 2) * 3,
    format("  (1 + 2) * 3   读成 ", []),
    write_canonical(T2),
    nl,

    % - 是 yfx（左结合），所以 1-2-3 读成 (1-2)-3
    T3 = 1 - 2 - 3,
    format("  1 - 2 - 3     读成 ", []),
    write_canonical(T3),
    nl,

    % ** 是 xfx（非结合），所以 1**2**3 是语法错误，必须加括号
    T4 = 2 ** 3,
    format("  2 ** 3        读成 ", []),
    write_canonical(T4),
    nl,
    say("  注意 ** 是 xfx：1 ** 2 ** 3 直接是语法错误，必须写 (1**2)**3。"),
    say("  （而且 ** 两套引擎的结果类型不一样，第 07 章已经说过，本教程不用它。）").

%% ---------------------------------------------------------------------------
%%  三、自定义运算符
%% ---------------------------------------------------------------------------
demo_custom :-
    say("---- 3. 自定义运算符 ----"),

    % xfx：非结合，两边不能出现同优先级的本运算符
    T1 = (a ===> b),
    format("  a ===> b        读成 ", []),
    write_canonical(T1),
    nl,

    % xfy：右结合
    T2 = (a vv b vv c),
    format("  a vv b vv c     读成 ", []),
    write_canonical(T2),
    nl,

    % yfx：左结合
    T3 = (a ww b ww c),
    format("  a ww b ww c     读成 ", []),
    write_canonical(T3),
    nl,

    % fy：前缀
    T4 = must go,
    format("  must go         读成 ", []),
    write_canonical(T4),
    nl,

    say("  自定义运算符让 DSL 读起来像自然语言的写法："),
    say("    if X > 0 then positive"),
    say("    但它是纯语法，不会自动给你任何语义 —— 语义还得自己写谓词。"),
    say("  工程建议：只在定义清晰的 DSL 里用，别乱占优先级空间。"),

    % 自定义运算符照样能用 =.. 拆
    T1 =.. L,
    format("  自定义运算符也能 =.. 拆开：~w~n", [L]).

%% ---------------------------------------------------------------------------
%%  四、查引擎认不认：current_op/3
%% ---------------------------------------------------------------------------
check_op(P, T, N) :-
    format("  ~w ~w ~q", [P, T, N]),
    (   current_op(P, T, N)
    ->  say("   -> 引擎确认")
    ;   say("   -> 引擎不认")
    ).

demo_table :-
    say("---- 4. 常用运算符的优先级（current_op/3 实测）----"),
    check_op(1200, xfx, ':-'),
    check_op(1200, xfx, '-->'),
    check_op(1100, xfy, ';'),
    check_op(1050, xfy, '->'),
    check_op(1000, xfy, ','),
    check_op(900,  fy,  '\\+'),
    check_op(700,  xfx, '='),
    check_op(700,  xfx, 'is'),
    check_op(700,  xfx, '=..'),
    check_op(600,  xfy, ':'),
    check_op(500,  yfx, '+'),
    check_op(400,  yfx, '*'),
    check_op(200,  xfx, '^'),
    check_op(200,  fy,  '-'),
    check_op(700,  xfx, '===>'),
    say("  这三张表（优先级 / 类型 / 名字）就是 Prolog 语法的全部秘密。"),
    say("  xfx 的一行里不能出现两个同优先级的 xfx 运算符 —— 这就是"),
    say("  第 11 章里 (X ===> Y) = (a ===> b) 必须加括号的原因。"),
    say("  也是初学者最容易撞到的坑：700 xfx 的 = 遇上一堆自定义运算符。"),
    say("  要可移植，就永远用括号把优先级讲清楚，别指望读者记住数字。"),
    say("  （顺便：:- op(P, xfx, '===>') 在两种引擎上都能生效，可以放心用。）").

%% ---------------------------------------------------------------------------
%%  入口
%% ---------------------------------------------------------------------------
main :-
    (   catch(run, E, (format(user_error, "*** 异常: ~q~n", [E]), halt(1)))
    ->  halt(0)
    ;   format(user_error, "*** run/0 失败~n", []),
        halt(1)
    ).

run :-
    format("==== 16 开始 ====~n", []),
    say("运算符只是「为了少打括号」的语法糖，底层一律是复合项。"),
    say(""),

    demo_sugar,  say(""),
    demo_parse,  say(""),
    demo_custom, say(""),
    demo_table,  say(""),

    format("==== 16 结束 ====~n", []).
