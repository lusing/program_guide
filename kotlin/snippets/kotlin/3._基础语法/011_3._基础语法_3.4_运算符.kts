// 算术运算
val sum = 10 + 5
val diff = 10 - 5
val product = 10 * 5
val quotient = 10 / 5
val remainder = 10 % 3

// 比较运算
val equal = (a == b)
val notEqual = (a != b)
val greater = (a > b)
val less = (a < b)

// 逻辑运算
val andResult = true && false
val orResult = true || false
val notResult = !true

// 区间运算
val range = 1..10        // 1 到 10 (包含)
val halfRange = 1 until 10 // 1 到 9 (不包含)
val stepRange = 1..10 step 2 // 1, 3, 5, 7, 9
