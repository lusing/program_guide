C     ============================================================
C     70 - 固定格式（fixed form）：1970 年代的 Fortran 长什么样
C
C     源文件用 .f 后缀，脚本会改用 -std=legacy 编译。这不是考古
C     表演：气象、核工程、油气勘探领域至今有海量 FORTRAN 77 代码
C     在生产环境天天运行，读得懂它们是这项技能的硬需求。
C
C     版面规则（来自打孔卡片时代，一张卡片 80 列）：
C       第 1 列      C 或 *  —— 整行是注释
C       第 1-5 列    语句标号（右对齐）
C       第 6 列      续行标志（非空格即表示接上一行）
C       第 7-72 列   语句正文（只有这 66 列是给代码的！）
C       第 73-80 列  卡片序号区（编译器无视，但 72 列上限还在）
C     对照文件: 71-legacy-features.f（老特性）与 01-basics.f90（现代写法）
C     ============================================================
      PROGRAM FIXFORM
      REAL AVG
      INTEGER I, N
      DOUBLE PRECISION S

C     ---- 1) 声明其实可以省略：I..N 开头默认整数，其余默认实数 ----
C     这是隐式类型规则（详见 71 示例），这里明确写出来只是习惯好
      WRITE (*, 9000) '==== 70: 固定格式演示 ===='

C     ---- 2) 带语句标号的 DO 循环：终点是一个标号，不是 END DO ----
C     「DO 100 I = 1, 10」读作：循环体到标号 100 那行为止。
C     老代码几乎总把标号 100 的那行写成 CONTINUE，纯粹当锚点用。
      S = 0.0D0
      DO 100 I = 1, 10
         S = S + DBLE(I)
  100 CONTINUE
      WRITE (*, 9001) 'DO 100 / CONTINUE : 1+...+10 =', S

C     ---- 3) 续行：第 6 列放一个非空格字符，语句接着上一行写 ----
C     下面第二行的加号在第 6 列，所以两行是同一条赋值语句。
C     72 列写不下长公式时就这么折行 —— 这是那 66 列带来的最日常的麻烦。
      AVG = S / 10.0
     +       - 0.0D0
      WRITE (*, 9001) '第 6 列续行（跨两行的赋值）:', AVG

C     ---- 4) 算术 IF：按表达式 <0 / =0 / >0 跳到三个标号之一 ----
C     一行同时承担「判断」和「跳转」，现代 Fortran 已列为废弃特性，
C     新代码写 if / else if / end if。读老代码时认得它就行：
      N = -3
      IF (N) 200, 210, 220
  200 WRITE (*, 9002) '算术 IF  : N<0 跳到标号 200, N =', N
      GOTO 230
  210 WRITE (*, 9002) '算术 IF  : N=0 跳到标号 210, N =', N
      GOTO 230
  220 WRITE (*, 9002) '算术 IF  : N>0 跳到标号 220, N =', N
  230 CONTINUE

C     ---- 5) 计算 GOTO：按 I 的取值在括号里挑第几个标号跳 ----
C     相当于跳转表版的 select case。I=2 就跳括号里第 2 个标号。
      I = 2
      GOTO (300, 310, 320), I
  300 WRITE (*, 9000) '计算 GOTO: I=1 会走这里'
      GOTO 330
  310 WRITE (*, 9000) '计算 GOTO: I=2 走这里'
      GOTO 330
  320 WRITE (*, 9000) '计算 GOTO: I=3 会走这里'
  330 CONTINUE

C     ---- 6) FORMAT 语句：老代码的输出全靠它，标号就是它的名字 ----
C     WRITE (*, 9001) 里的 9001 就是下面这条 FORMAT 的标号。
C     1X 是「先空一格」（走纸控制的历史遗产），A 接字符串，F8.1 接实数。
      WRITE (*, 9003) 42
 9003 FORMAT (1X, 'FORMAT 9003 拿到整数 ', I0)
      WRITE (*, 9000) '==== 70 结束 ===='

 9000 FORMAT (1X, A)
 9001 FORMAT (1X, A, F8.1)
 9002 FORMAT (1X, A, I4)
      END
