"""第 01 章：样本空间、事件运算与有限 σ 代数。"""
from itertools import combinations
from fractions import Fraction


def powerset(s):
    items = tuple(s)
    return frozenset(
        frozenset(items[i] for i in idx)
        for r in range(len(items) + 1)
        for idx in combinations(range(len(items)), r)
    )


def is_sigma_algebra(events, omega):
    events = frozenset(frozenset(e) for e in events)
    if frozenset() not in events or frozenset(omega) not in events:
        return False
    for a in events:
        if frozenset(omega) - a not in events:
            return False
    for a in events:
        for b in events:
            if a | b not in events:
                return False
    return True


print("==== 01 events")
omega = frozenset(range(1, 7))
A = {2, 4, 6}
B = {4, 5, 6}
assert A | B == {2, 4, 5, 6}
assert A & B == {4, 6}
assert omega - A == {1, 3, 5}
assert A - B == {2}
assert (A | B) == (omega - ((omega - A) & (omega - B)))
print("die events: union, intersection, complement, De Morgan: OK")

trivial = [frozenset(), omega]
assert is_sigma_algebra(trivial, omega)
print("trivial sigma-field {empty, Omega}: OK")

small_omega = frozenset({1, 2, 3})
power = powerset(small_omega)
assert len(power) == 8
assert is_sigma_algebra(power, small_omega)
print("power set of a 3-point space has 8 events and is a sigma-field: OK")

generated = frozenset([frozenset(), frozenset(A), omega - A, omega])
assert is_sigma_algebra(generated, omega)
assert generated == frozenset([frozenset(), frozenset(A), frozenset({1,3,5}), omega])
print("sigma-field generated by one die event has four answers: OK")

partition = [{1}, {2, 3}, {4, 5, 6}]
assert frozenset().union(*partition) == omega
assert all(x & y == frozenset() for i, x in enumerate(partition)
           for y in partition[i + 1:])
P = lambda E: Fraction(len(E), len(omega))
assert P(A) == Fraction(1, 2)
assert P(A & B) == Fraction(1, 3)
print("uniform finite probability: P(even)=1/2, P(even and >=4)=1/3: OK")
print("END ====")
