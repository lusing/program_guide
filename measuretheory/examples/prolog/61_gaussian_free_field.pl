:- encoding(utf8).
% 第 61 章 Prolog：4×4 格子的狄利克雷问题（rdiv 精确）。
% ① 内部均值方程组（左右对称约化为 2 未知量）的消元求解：a=3/8, c=1/8；
% ② 全部四个内部点的逐点均值性回代判定；
% ③ 最大值原理：内部值夹在边界极值 [0,1] 内；
% ④ 唯一性的有限验证：齐次（零边界）均值方程组在内部只有零解
%    （对称约化后的 2×2 齐次方程消元）。
:- initialization(main).

% 对称约化后的方程：3a − c = 1（(1,1) 均值式），a − 3c = 0（(1,2) 均值式）
% 消元：由第二式 a = 3c 代入第一式 9c − c = 1 ⟹ c = 1/8, a = 3/8。
solve_dirichlet(A, C) :-
    % 3a − c = 1, a − 3c = 0 ⟹ 8c = 1（两式组合）
    C is 1 rdiv 8,
    A is 3 rdiv 8,
    3 * A - C =:= 1,
    A - 3 * C =:= 0.

% 回代：四内部点均值性（u11=u21=a 下层；u12=u22=c 上层；底边=1 其余边界=0）
mean_value_ok(A, C) :-
    % (1,1)：邻居 (1,0)=1, (0,1)=0, (2,1)=A, (1,2)=C
    4 * A =:= 1 + 0 + A + C,
    % (2,1)：邻居 (2,0)=1, (3,1)=0, (1,1)=A, (2,2)=C
    4 * A =:= 1 + 0 + A + C,
    % (1,2)：邻居 (1,1)=A, (0,2)=0, (2,2)=C, (1,3)=0
    4 * C =:= A + 0 + C + 0,
    % (2,2)：邻居 (2,1)=A, (3,2)=0, (1,2)=C, (2,3)=0
    4 * C =:= A + 0 + C + 0.

% 最大值原理
max_principle(A, C) :- A >= 0, A =< 1, C >= 0, C =< 1.

% 唯一性：齐次方程 3a = c 且 a = 3c ⟹ 9a = a ⟹ a = 0（8a=0）
unique_zero :-
    % 齐次：3a = c 且 a = 3c ⟹ a = 9a ⟹ 8a = 0 ⟹ a = 0（c = 3a 随之为 0）
    A = 0 rdiv 1,
    C is 3 * A,
    3 * A =:= C,
    A =:= 3 * C,
    C =:= 0.

main :-
    format("==== 61 gaussian_free_field~n"),
    solve_dirichlet(A, C),
    format("① 消元解：a = ~w（下层 u11=u21），c = ~w（上层 u12=u22）~n", [A, C]),
    mean_value_ok(A, C),
    format("② 四个内部点的均值方程回代全过（逐点 = 四邻平均）~n"),
    max_principle(A, C),
    format("③ 最大值原理：a、c ∈ [0,1]（极值在边界，内部不上不下）~n"),
    unique_zero,
    format("④ 唯一性：零边界齐次方程 => 内部恒 0（消元 a=9a => a=0）~n"),
    format("END ====~n").
