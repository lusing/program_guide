# 第 06 章 基数算术：ℵ_α^ℵ_β 计算器（定理 19 的规则引擎）
#
# Jech 定理 19 给出 ℵ_α^ℵ_β 的归纳计算三分支：
#   (i)  α ≤ β：ℵ_α^ℵ_β = 2^ℵ_β
#   (ii) 存在 γ<α 使 ℵ_γ^ℵ_β ≥ ℵ_α：ℵ_α^ℵ_β = sup{ℵ_γ^ℵ_β : γ<α}
#   (iii) 否则（α>β 且全部 ℵ_γ^ℵ_β < ℵ_α）：
#         ℵ_α^ℵ_β = ℵ_α^cf ℵ_α ...（按 cf ℵ_α 与 ℵ_β 的大小再分）
# 本文件实现符号规则引擎（以序数对 (α,β) 为输入，输出分支判定
# 与化简路线），并给出 Hausdorff 公式的实例演算。

import sys
import io

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

print("==== 06 基数算术：ℵ^ℵ 计算器")

# ------------------------------------------------------------------
# 一、定理 19 的分支判定
# ------------------------------------------------------------------

def branch(alpha, beta):
    """返回 (i/ii/iii) 分支与说明。alpha, beta 是序数描述串。"""
    if alpha <= beta:
        return ("i", f"ℵ_{alpha}^ℵ_{beta} = 2^ℵ_{beta}")
    # ii/iii 的区分需要比较 sup{ℵ_γ^ℵ_β : γ<α} 与 ℵ_α——
    # 符号层面用 cf 信息演示
    return ("ii/iii", f"按 sup{{ℵ_γ^ℵ_{beta} : γ<{alpha}}} 与 ℵ_{alpha} 的关系再分")

cases = [(0, 0), (0, 1), (1, 1), (1, 0), (2, 1), ("ω", "ω"), ("ω+1", "ω")]
for a, b in cases:
    br, desc = branch(a, b) if isinstance(a, str) is False else ("符号", "")
    if isinstance(a, str):
        br, desc = branch(0, 0) if a <= b else ("ii/iii", "")
    print(f"  ℵ_{a}^ℵ_{b} → 分支 {br}：{desc}")

# ------------------------------------------------------------------
# 二、Hausdorff 公式的实例（(6.18)）
#     ℵ_{α+1}^ℵ_β = ℵ_{α+1}^ℵ_{β-1} · ℵ_α^ℵ_β   （β < α+1 时）
#     特例：ℵ_{n+1}^ℵ_0 = max(ℵ_{n+1}, ℵ_n^ℵ_0) = ℵ_{n+1}
# ------------------------------------------------------------------

print("\nHausdorff 链（ℵ_α 为后继基数、指数递降）：")
print("  ℵ_1^ℵ_0 = ℵ_1   （ℵ_1 正则，ℵ_0 < ℵ_1）")
print("  ℵ_2^ℵ_0 = ℵ_2")
print("  ℵ_2^ℵ_1 = ℵ_2   （后继基数正则，指数 < 基数 ⟹ 坍缩）")
print("  ℵ_ω^ℵ_0 = sup_n ℵ_n^ℵ_0 = ℵ_ω   （cf ℵ_ω = ω）")
print("  ℵ_ω^ℵ_1 = ?     （cf ℵ_ω = ω < ℵ_1 ⟹ 走分支 (iii)）")

# ------------------------------------------------------------------
# 三、König 推论的数值影子：cf(2^κ) > κ
# ------------------------------------------------------------------

# 有限代理：2^n 的"达到方式"需要多于 n 步
print("\nKönig 推论 2 的代理：cf(2^n) > n")
for n in [3, 5, 8]:
    target = 2 ** n
    # 用递增序列逼近 target 至少需要 ceil(log2) 步（倍增策略）
    steps_double = 0
    v = 1
    while v < target:
        v *= 2
        steps_double += 1
    print(f"  n={n}：2^n={target}，倍增逼近需 {steps_double} 步 ≥ log2")
    assert steps_double <= n  # 有限域倍增快于 n；无穷域反转为严格慢于 κ
print("  （有限域倍增快；无穷域 König 断言任何逼近序列长度 > κ——")
print("   有限直觉的失效方向正好相反，是本章的元教训。）")

