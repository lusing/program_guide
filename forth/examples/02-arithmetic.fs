cr cr .( ---- 进制 ----) cr

\ 关键点：base 同时影响「读入」和「输出」两个方向
cr cr .( 当前 base = ) base @ .
cr .( base=16 时，源码里的 ff 会被当成 ) hex ff decimal u.
cr .( base=2  时，源码里的 101 会被当成 )  2 base ! 101 decimal u.
cr .( base=36 是上限，zz = )  #36 base ! zz decimal u.   \ 35*36+35 = 1295
cr .( 现在 base 已复位为 ) base @ .

\ 安全写法：临时切进制，用完恢复
: .hex  ( n -- )  base @ >r hex        u.  r> base ! ;
: .bin  ( n -- )  base @ >r 2 base !   u.  r> base ! ;

cr cr .( 48879 的十六进制 = ) 48879 .hex
cr .( 170   的二进制     = )   170 .bin
cr .( 255   的十六进制 = )    255 .hex
cr .( 用完记得复位，现在 base = ) base @ .

