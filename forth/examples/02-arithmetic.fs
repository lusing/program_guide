\ 把「分」为单位的整数打印成 "¥123.45"
\ 注意：# 系列是从最低位往回拼的，所以代码里的顺序和实际显示顺序相反
: .money  ( 分 -- )
  ." ¥"
  s>d <#                    \ 转成双精度，开始拼装
       #  #                 \ 两位小数
       [char] . hold        \ 小数点
       #s                   \ 剩余所有位
  #>  type ;                \ 收尾，得到 addr u

cr .( 12345 分 => ) 12345 .money
cr cr .( 5 分   => )     5 .money
cr cr .( 100 分 => )   100 .money

\ 固定 8 位右对齐，前导 0
: .8digits  ( n -- )  s>d <# # # # # # # # # #> type ;
cr cr .( 42 补零到 8 位 => ) 42 .8digits

