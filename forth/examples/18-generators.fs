cr cr .( ---- 小结 ----) cr

: summary  ( -- )
  cr ." 生成器 = 数据区 + 取下一个词。就这么简单。"
  cr ." 好处："
  cr ."   - 内存占用恒定，不生成中间数组"
  cr ."   - 能表达无限序列"
  cr ."   - 组合子能像管道一样串起来"
  cr ." 代价："
  cr ."   - 每个生成器都要手写一块数据区，比 Python 的 yield 啰嗦"
  cr ."   - 数据区分配在字典里，用完不会释放"
  cr ."     （真要回收就改用 allocate/free，见 10-heap-alloc.fs）"
  cr ."   - 类型安全全靠自觉，栈注解一定要写清楚" ;

summary

