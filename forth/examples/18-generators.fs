#! /usr/bin/env gforth
\ ============================================================
\  18-generators.fs —— 生成器、迭代器与惰性序列
\  运行： gforth examples/18-generators.fs
\
\  Forth 没有 yield。但"生成器"这个概念很好用：
\  一次要一个值，不要一次生成一大堆。
\  这里用最 Forth 的方式实现它：数据区 + 一个"取下一个"的词。
\ ============================================================

cr .( ==== 18  生成器与惰性序列 ====) cr

\ ============================================================
\  协议约定
\ ============================================================
cr .( ---- 协议 ----) cr

\ 一个"生成器"是一对东西：
\   私有数据区的地址  +  一个"取下一个"的词
\
\   取下一个 的签名统一是  ( 数据区 -- n 还有吗 )
\     还有吗 = true  -> n 有效
\     还有吗 = false -> n 是 0，序列结束了
\
\ 所有生成器的私有数据区都取 3 个 cell，这样组合起来很整齐。
\
\ ⚠ 坑：别指望用 :noname 做闭包。
\   gforth 的 locals 是运行时从栈上取的，不会"捕获"外层变量；
\   想让匿名词记住点什么，只能把数据放在字典/堆里，再把地址传进去。

3 cells constant 生成器大小

\ ============================================================
\  一、计数器生成器
\ ============================================================
cr .( ---- 计数器 ----) cr

\ 数据区： [当前值][步长][上限]
: 造计数器  ( 起点 步长 上限 -- 数据区 )
  here >r                            \ 记下数据区地址
  rot ,  swap ,  ,                   \ 存 当前值 / 步长 / 上限
  r> ;

: 计数器取下一个  { st -- n 还有吗 }
  st @  st 2 cells + @  >            \ 当前值 > 上限？
  if    0 false
  else  st @                         \ 产出当前值
        st dup @  st cell+ @  +  swap !   \ 当前值 += 步长
        true
  then ;

\ ============================================================
\  二、斐波那契生成器
\ ============================================================
cr .( ---- 斐波那契 ----) cr

\ 数据区： [a][b][还剩几个]
: 造斐波那契  ( 个数 -- 数据区 )
  here >r
  0 ,  1 ,  ,                        \ a=0  b=1  剩余=个数
  r> ;

: 斐波那契取下一个  { st -- n 还有吗 }
  st 2 cells + @  0=  if  0 false  exit  then
  st @                               \ 产出 a
  st @  st cell+ @  +                \ a+b
  st cell+ @  st  !                  \ a <- 旧 b
  st cell+ !                         \ b <- a+b
  -1 st 2 cells +  +!                \ 还剩几个 -1
  true ;

\ ============================================================
\  三、遍历数组
\ ============================================================
cr .( ---- 遍历数组 ----) cr

create 数据  1 , 2 , 3 , 4 , 5 , 6 ,

\ 数据区： [当前地址][元素个数][已取个数]
: 造数组遍历  ( addr 个数 -- 数据区 )
  here >r  swap ,  ,  0 ,  r> ;

: 数组取下一个  { st -- n 还有吗 }
  st 2 cells + @  st cell+ @  >=  if  0 false  exit  then
  st @ @                             \ 取当前元素
  st dup @  cell+  swap !            \ 地址前进一格
  1 st 2 cells +  +!
  true ;

\ ============================================================
\  四、消费者：把生成器跑完
\ ============================================================
cr .( ---- 消费者 ----) cr

: 逐个打印  ( 数据区 xt -- )
  begin
    2dup execute                     \ ( 数据区 xt n 还有吗 )
  while
    .                                \ 打印 n；栈上回到 ( 数据区 xt )
  repeat
  2drop drop ;                       \ 丢掉 数据区 xt 和最后那个 n

create 收集缓冲  256 cells allot
0 value 收集个数

: 收集  ( 数据区 xt -- addr 个数 )
  0 to 收集个数
  begin
    2dup execute
  while
    收集个数 cells 收集缓冲 + !
    收集个数 1+ to 收集个数
  repeat
  2drop drop
  收集缓冲  收集个数 ;

: consume-demo  ( -- )
  cr ." 1 到 5：        " 1 1 5 造计数器  ['] 计数器取下一个 逐个打印
  cr ." 0 3 6 9 12：    " 0 3 12 造计数器 ['] 计数器取下一个 逐个打印
  cr ." 斐波那契前 10：  " 10 造斐波那契  ['] 斐波那契取下一个 逐个打印
  cr ." 数组 6 个元素：  " 数据 6 造数组遍历 ['] 数组取下一个 逐个打印

  cr ." 收集成数组："
  1 1 5 造计数器 ['] 计数器取下一个 收集
  dup ."   个数 = " . ."   内容 = "
  0 ?do  dup i cells + @ .  loop  drop ;

