\ ============================================================
\  五、组合子：把生成器变成新的生成器
\ ============================================================
cr cr .( ---- 组合子 ----) cr

\ ⚠ 坑：下面每个"取下一个"的词都必须定义在对应的"造X"之前 ——
\       造X 里的 ['] 是编译期查词，那时候它就得存在。

\ 映射：数据区 [源数据区][源xt][变换xt]
: 映射取下一个  { st -- n 还有吗 }
  st @  st cell+ @  execute          \ 问源要一个   ( n 还有吗 )
  if    st 2 cells + @  execute  true      \ 变换一下，返回
  else  drop  0 false               \ ⚠ 坑：这里必须 drop 掉源给的占位值，
  then ;                            \       否则每次跑完栈上都会多留一个 0

: 造映射  ( 源数据区 源xt 变换xt -- 新数据区 新xt )
  here >r  rot ,  swap ,  ,  r>  ['] 映射取下一个 ;

\ 过滤：数据区 [源数据区][源xt][谓词xt]
\ ⚠ 坑：用 begin ... again 加显式 exit 比 begin ... until 好写，
\       until 那个分支要小心别让栈越滚越长。
: 过滤取下一个  { st -- n 还有吗 }
  begin
    st @  st cell+ @  execute       \ ( n 源的还有吗 )
    0= if  drop  0 false  exit  then
    dup  st 2 cells + @  execute    \ ( n 留下吗 )
    if   true  exit  then
    drop                            \ 不要这个，丢掉再来
  again ;

: 造过滤  ( 源数据区 源xt 谓词xt -- 新数据区 新xt )
  here >r  rot ,  swap ,  ,  r>  ['] 过滤取下一个 ;

\ 截断：只取前 n 个
: 截断取下一个  { st -- n 还有吗 }
  st 2 cells + @  0=  if  0 false  exit  then
  -1 st 2 cells +  +!
  st @  st cell+ @  execute ;

: 造截断  ( 源数据区 源xt n -- 新数据区 新xt )
  here >r  rot ,  swap ,  ,  r>  ['] 截断取下一个 ;

: square  ( n -- n )  dup * ;
: odd?    ( n -- flag )  1 and ;

