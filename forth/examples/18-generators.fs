\ ============================================================
\  七、生产者-消费者：用生成器搭管道
\ ============================================================
cr cr .( ---- 管道 ----) cr

\ 管道就是一层层套起来的组合子。
\ 这里做个有点用的：统计一段话里各个词性的"词长分布"。

\ ⚠ 坑：," 造的是 counted string —— 第一个字节是长度。
\       直接 `样本 长度 type` 会把那个长度字节也打印出来（显示成一个怪字符）。
\       要用 count 把 ( 地址 长度 ) 取出来。
create 样本 ," the quick brown fox jumps over the lazy dog"
样本 count 2constant 样本内容

\ 数据区： [地址][剩余长度]
: 造字符流  ( addr u -- 数据区 )
  here >r  swap ,  ,  r> ;

: 字符流取下一个  { st -- c 还有吗 }
  st cell+ @  0=  if  0 false  exit  then
  st @ c@                            \ 产出当前字符
  st dup @ 1+ swap !                 \ 地址 +1
  -1 st cell+ +!                     \ 剩余 -1
  true ;

: 是空格?  ( c -- flag )  bl = ;
: 非空格?  ( c -- flag )  bl > ;

0 value 空格数

: 数空格  ( -- )
  0 to 空格数
  样本内容 造字符流  ['] 字符流取下一个
  begin
    2dup execute
  while
    是空格?  if  1 空格数 + to 空格数  then
  repeat
  2drop drop ;

: pipe-demo  ( -- )
  cr ." 样本：[" 样本内容 type ." ]"
  cr ." 跳过空格后的前 12 个字符："
      样本内容 造字符流  ['] 字符流取下一个
      ['] 非空格?  造过滤
      12 造截断
      begin  2dup execute  while  emit  repeat
      2drop drop
  数空格
  cr ." 空格的个数： " 空格数 .
  cr ." 样本里一共 " 样本内容 nip . ." 个字符" ;

