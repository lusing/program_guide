\ ---- 栈效应注释约定 ----
\ ( 之前的数据 -- 之后的数据 )    例如 swap 是 ( a b -- b a )

\ ============================================================
\  一、数据栈：Forth 的全部"变量传递"都靠它
\ ============================================================
cr cr .( ---- 数据栈操作 ----) cr
cr .( 左边是输入的栈，右边是执行后的结果) cr

\ 演示辅助词：打印当前数据栈，然后清空，方便下一条从头开始
: demo  ( ... -- )  .s cr  clearstack ;

cr .( push 1 2 3   )  1 2 3       demo
cr .( drop  丢弃顶 )  1 2 3 drop  demo
cr .( dup   复制顶 )  1 2 dup     demo
cr .( over  复制次 )  1 2 over    demo
cr .( swap  交换   )  1 2 swap    demo
cr .( nip   丢次顶 )  1 2 nip     demo
cr .( tuck  插次顶 )  1 2 tuck    demo
cr .( rot   三旋转 )  1 2 3 rot   demo
cr .( -rot  逆旋转 )  1 2 3 -rot  demo
cr .( 2dup 复制两个)  1 2 2dup    demo
cr .( 2drop丢两个  )  1 2 3 2drop demo
cr .( 2over复制次对)  1 2 3 4 2over demo
cr .( 2swap交换两对)  1 2 3 4 2swap demo

cr cr .( 随机访问：pick / roll，下标从 0 开始) cr
cr .( 0 pick == dup )  7 8 9 0 pick demo
cr .( 2 pick 复制第3个) 7 8 9 2 pick demo
cr .( 2 roll 抽出第3个) 7 8 9 2 roll demo

cr cr .( depth 当前栈深度 )  10 20 30 depth . cr  clearstack

\ ============================================================
\  二、返回栈：借用正则返回地址栈做临时暂存
\ ============================================================
cr cr .( ---- 返回栈（临时寄存器）----) cr

: r-demo  ( -- )
  100 >r  200 >r              \ 借返回栈存两个数
  ." r@    = " r@ . cr        \ 看栈顶（不弹出）
  ." 2r@   = " 2r@ swap . . cr
  r> r>                       \ 必须成对取回！返回栈不平衡会崩溃
  ." 取回  = " . . cr ;
r-demo

: swap-via-r  ( a b -- b a )  >r  r> swap ;   \ 其实等价于 swap
." swap-via-r 1 2 -> " 1 2 swap-via-r . . cr

\ ============================================================
\  三、浮点数有独立的浮点栈
\ ============================================================
cr .( ---- 浮点栈 ----) cr
1.5e0 2.25e0   cr .( 入栈 1.5 2.25 -> ) f.s cr
f+             cr .( f+             -> ) f.s cr
fdup f*        cr .( fdup f*        -> ) f.s cr
fsqrt          cr .( fsqrt          -> ) f.s cr
f.  cr                                \ 打印并弹出
cr .( 浮点栈现在为空：) f.s cr

\ ============================================================
\  四、实战：用栈把摄氏温度转华氏
\ ============================================================
cr .( ---- 小练习 ----) cr

: c>f  ( c -- f )  9 * 5 / 32 + ;
: f>c  ( f -- c )  32 - 5 * 9 / ;

." 100 摄氏度 = " 100 c>f . ." 华氏度" cr
." 212 华氏度 = " 212 f>c . ." 摄氏度" cr
." 37  摄氏度 = "  37 c>f . ." 华氏度（体温）" cr

cr .( ==== 01 结束，栈应当是空的：) .s cr
bye
