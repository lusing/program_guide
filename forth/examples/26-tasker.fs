\ ============================================================
\  一、世界观：协作式 = 每个任务都自觉 pause
\ ============================================================
cr cr .( ---- 世界观 ----) cr

: theory  ( -- )
  cr ." · 抢占式（Windows/Linux）：时钟中断随时切走你——共享要加锁"
  cr ." · 协作式（Forth 传统）：任务必须自己喊 pause 才让位——"
  cr ."   没人抢，天然确定，代码里不用一把锁"
  cr ." · PC/FORTH 2.0 当年就是 1 个前台任务 + 10 个后台任务："
  cr ."   前台等键盘的空档，轮流跑后台"
  cr ." gforth 把这套做进了 tasker.fs：NewTask / activate / pause / kill" ;
theory

\ ============================================================
\  二、最小双任务：activate 的「双返回」
\ ============================================================
cr cr .( ---- 最小双任务 ----) cr

variable 共计

\ ⚠ 两个铁律（本机实测，见坑清单）：
\   1. activate 只能在冒号定义里调——顶层调会把主任务返回栈搞烂，挂死
\   2. activate 的语义是「双返回」：主任务从这句话直接跳出所在词；
\      新任务则从这句话【后面】开始跑。启动词是固定套式，五步走：

\ ① 造任务（栈大小 4096，出生时睡着）
4096 NewTask constant 任务甲
4096 NewTask constant 任务乙

\ ② 写工人的活（循环里必须有 pause，否则独吞 CPU）
: 工人  ( -- )  6 0 do  1 共计 +!  ." w"  pause  loop ;

\ ③ 排程词：activate 之后的代码【只属于新任务】
: 排程甲  ( -- )  任务甲 activate  工人 ;
: 排程乙  ( -- )  任务乙 activate  工人 ;

\ ④ 主任务自己的循环也要 pause
: 主循环  ( -- )  6 0 do  ." M"  pause  loop ;

\ ⑤ 点火
: demo  ( -- )
  排程甲                     \ 主任务：activate 后直接从排程甲返回
  排程乙
  主循环                     \ MwMwMw... 主/甲/乙 交替
  cr ;
demo
cr ." 交替结束，共计 = " 共计 @ . cr

\ ============================================================
\  三、user 变量：每个任务一份的「全局」
\ ============================================================
cr cr .( ---- user 变量隔离 ----) cr

\ user 造的变量物理上住在本任务的 user 区里——
\ 每个任务各有一份，互不可见。这正是多任务不撕破脸的秘密。
user 任务号

: 报数  ( -- )  4 0 do  任务号 @ . space  pause  loop ;
4096 NewTask constant 任务丙
4096 NewTask constant 任务丁

: 排程丙  ( -- )  任务丙 activate  3 任务号 !  报数 ;
: 排程丁  ( -- )  任务丁 activate  4 任务号 !  报数 ;

: demo2  ( -- )
  9 任务号 !                 \ 主任务自己的副本设成 9
  排程丙  排程丁
  4 0 do  任务号 @ . space  pause  loop ;
demo2
\ 轮转顺序由任务入链顺序决定：主 9、丁 4、丙 3 一轮轮转——
\ 三个号各自稳定，互不串扰：user 区人手一份
cr cr ." （主=9、丁=4、丙=3，各读各的——user 区人手一份）" cr

\ ============================================================
\  四、任务的死亡：自然结束 vs kill
\ ============================================================
cr cr .( ---- 任务死亡 ----) cr

\ ⚠ 坑（本机实测）：任务跑完自然结束时会 kill-task 自杀并 free 掉
\   自己的内存——之后你再对它 kill 就是 double free（glibc 直接报
\   double free or corruption）。只 kill 还活着的任务。
variable 乙计数
: 长工  ( -- )  100 0 do  1 乙计数 +!  pause  loop ;
4096 NewTask constant 任务戊

: 排程戊  ( -- )  任务戊 activate  长工 ;

: demo3  ( -- )
  排程戊
  4 0 do  pause  loop        \ 让长工跑几个回合
  任务戊 kill                \ 还活着：正常杀
  ." 杀掉了任务戊，它跑了 " 乙计数 @ . ." 个回合" cr ;
demo3

\ 都结束了？single-tasking? 告诉你现在链上还剩几个
: demo4  ( -- )
  single-tasking? if  ." 链上只剩主任务一个了" cr
                 else  ." 链上还有别人" cr  then ;
demo4

\ ============================================================
\  小结
\ ============================================================
cr cr .( ---- 小结 ----) cr

: recap  ( -- )
  cr ." 1. activate 只能进冒号定义，且是「双返回」套式："
  cr ."      任务 activate  新任务代码   ——主任务跳出去，新任务续跑"
  cr ." 2. 协作式：谁的循环里没写 pause，谁就独吞 CPU"
  cr ." 3. user 变量每任务一份——多任务的『局部全局』"
  cr ." 4. 自然结束的任务自己 free 自己；别对尸体再 kill"
  cr ." 5. tasker.fs 会把 key/emit/type 都换成带 pause 的版本" ;
recap

cr cr .( ==== 26 结束，栈为空：) .s cr
bye
