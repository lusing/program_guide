\  四、命名：起名就是设计（Brodie 第 5 章 Choosing Names）
\ ============================================================
cr cr .( ---- 命名 ----) cr

\ 反面：过程式流水账名，暴露实现而不是意图
: proc2  ( a b -- n )  2* swap 3 * + ;      \ 它到底算什么？

\ 正面：名字说出意图，实现随便换
: 总价  ( 单价 数量 -- n )  3 * swap 2* + ; \ 还是不行——魔法数藏了运费？

\ 再正面一点：把魔法数也请出来
2 constant 运费
: 含运费总价  ( 单价 数量 -- 总价 )
  over *          \ 单价×数量
  swap drop       \ 剩下积
  运费 + ;
: naming  ( -- )
  cr ." 起名的过程会逼你想清楚这个词的边界——"
  cr ." 想不清楚的名字 = 想不清楚的设计。" cr ;
naming

