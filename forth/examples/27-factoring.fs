\ 版本 1（反面教材）：13 段雷同的 begin/while 一路堆下去，
\ 每段只是「值」和「符号」不同——复制粘贴的坏味道扑面而来：
: 罗马-丑  ( n -- )
  begin dup 1000 >= while ." M" 1000 - repeat
  begin dup 900 >=  while ." CM" 900 -  repeat
  begin dup 500 >=  while ." D" 500 -   repeat
  begin dup 400 >=  while ." CD" 400 -  repeat
  begin dup 100 >=  while ." C" 100 -   repeat
  begin dup 90 >=   while ." XC" 90 -   repeat
  begin dup 50 >=   while ." L" 50 -    repeat
  begin dup 40 >=   while ." XL" 40 -   repeat
  begin dup 10 >=   while ." X" 10 -    repeat
  begin dup 9 >=    while ." IX" 9 -    repeat
  begin dup 5 >=    while ." V" 5 -     repeat
  begin dup 4 >=    while ." IV" 4 -    repeat
  begin dup 1 >=    while ." I" 1 -     repeat
  drop ;

\ 版本 2：把「值/符号」提进数据表，代码只剩一个循环——
\ 这就是 Brodie 说的「数据结构能消灭控制结构」（第 8 章的主题）
create s-M   s" M" s,    create s-CM  s" CM" s,
create s-D   s" D" s,    create s-CD  s" CD" s,
create s-C   s" C" s,    create s-XC  s" XC" s,
create s-L   s" L" s,    create s-XL  s" XL" s,
create s-X   s" X" s,    create s-IX  s" IX" s,
create s-V   s" V" s,    create s-IV  s" IV" s,
create s-I   s" I" s,

create 罗马对
1000 , s-M ,   900 , s-CM ,   500 , s-D ,   400 , s-CD ,
100  , s-C ,    90 , s-XC ,    50 , s-L ,    40 , s-XL ,
10   , s-X ,     9 , s-IX ,     5 , s-V ,     4 , s-IV ,
1    , s-I ,

: 罗马值  ( i -- v )    2* cells 罗马对 + @ ;
: 罗马符  ( i -- caddr )  2* cells 罗马对 + cell+ @ ;

: 罗马-表  ( n -- )   \ 同一个答案，13 行变成 5 行
  13 0 do
    begin  dup i 罗马值 >=  while
      i 罗马符 count type
      i 罗马值 -
    repeat
  loop  drop ;

