\ ============================================================
\  一、自制断言库（零依赖，最实用）
\ ============================================================
cr .( ---- 断言库 ----) cr

0 value 通过数
0 value 失败数

: .绿  ( -- )  ." ✓" ;
: .红  ( -- )  ." ✗" ;

: 记通过  ( -- )  1  通过数 +  to 通过数 ;
: 记失败  ( -- )  1  失败数 +  to 失败数 ;

\ ⚠ 坑：断言词里别用 locals 的 { a b | c } 形式（0.7.3 会崩），
\       老老实实用 { a b } 或者纯栈操作。
: assert=  { 实际 期望 -- }
  实际 期望 =
  if   记通过
  else 记失败
       cr ."    " .红 ." 期望 " 期望 . ."  实际 " 实际 .
  then ;

: assert-深  ( d实际 d期望 -- )
  2over 2over  d=
  if   记通过  2drop 2drop
  else 记失败
       cr ."    " .红 ." 期望 " d. ."  实际 " 2swap d.
       2drop 2drop
  then ;

\ 浮点：gforth 没有 f=，而且 ——
\ ⚠ 坑：别用 f~ 做"相等"断言！
\       ANS 说 f~ 的 r3<0 表示绝对误差比较，但本机实测 0.7.3 上
\         f: 0.0e0 0.0e0 -1.0e-9 f~   ->  false （0 和 0 都不相等！）
\         f: 1.0e0 1.0e0 -1.0e-9 f~   ->  true
\       它的实际行为更接近相对误差，在 0 附近完全反直觉。
\       写测试就老老实实自己算： |实际-期望| < 容差
1.0e-9 fconstant 容差

: assert≈  ( f: 实际 期望 -- )  ( -- )
  fover fover f- fabs  容差 f<
  if   记通过  fdrop fdrop
  else 记失败
       cr ."    " .红 ." 期望 " fdup f. ."  实际 " fover f.
       fdrop fdrop
  then ;

: assert-栈空  ( -- )
  depth 0=
  if   记通过
  else 记失败
       cr ."    " .红 ." 栈上还剩 " depth . ." 个： "
       depth 0 ?do  depth i - 1- pick .  loop
  then ;

\ 检查某个词会不会抛出指定的异常码
: assert-抛出  ( xt 期望码 -- )
  { 期望码 }
  catch                              \ ( 实际码 ) 没抛则是 0
  dup 0=
  if   记失败  cr ."    " .红 ." 期望抛出异常 " 期望码 . ."  但它正常返回了"
       drop
  else 期望码 =
       if   记通过
       else 记失败
            cr ."    " .红 ." 期望异常码 " 期望码 . ."  实际 " dup .
       then
  then ;

: .汇总  ( -- )
  cr ." ────────────────────────────"
  cr ." 通过 " 通过数 . ."   失败 " 失败数 .
  失败数 0=
  if   cr .绿 ." 全部通过"
  else cr .红 ." 有失败项"
  then
  cr ." ────────────────────────────" ;

\ ============================================================
\  二、被测模块：一个带边界检查的栈
\ ============================================================
cr cr .( ---- 被测模块：安全栈 ----) cr

100 constant 栈容量
create 栈数据  栈容量 cells allot
0 value 栈顶

: 栈清空  ( -- )  0 to 栈顶 ;
: 栈深度  ( -- n )  栈顶 ;
: 栈空?   ( -- flag )  栈顶 0= ;
: 栈满?   ( -- flag )  栈顶 栈容量 >= ;

-200 constant 栈下溢
-201 constant 栈上溢

: 压栈  ( n -- )
  栈满?  if  栈上溢 throw  then
  栈数据 栈顶 cells +  !
  栈顶 1+ to 栈顶 ;

: 弹栈  ( -- n )
  栈空?  if  栈下溢 throw  then
  栈顶 1- to 栈顶
  栈数据 栈顶 cells + @ ;

: 看栈顶  ( -- n )
  栈空?  if  栈下溢 throw  then
  栈数据 栈顶 1- cells + @ ;

\ ============================================================
\  三、给这个栈写测试
\ ============================================================
cr cr .( ---- 测试套件 ----) cr

: 测-基本  ( -- )
  栈清空
  1 压栈  2 压栈  3 压栈
  弹栈  3 assert=
  弹栈  2 assert=
  弹栈  1 assert=
  栈空?    true assert=
  assert-栈空 ;

: 测-空栈弹出  ( -- )
  栈清空
  ['] 弹栈  栈下溢  assert-抛出
  assert-栈空 ;

\ ⚠ 坑：['] 是编译期查词，用到的词必须已经定义好。
\       下面这个 压满 就得写在引用它的 测-溢出 之前，
\       否则编译时就是 Undefined word —— 运行时才报错就晚了。
: 压满  ( -- )  栈容量 1+  0 ?do  i 压栈  loop ;

: 测-溢出  ( -- )
  栈清空
  ['] 压满  栈上溢  assert-抛出
  assert-栈空 ;

\ ⚠ 坑：测试之间要各写各的，别依赖前一个测试留下的状态。
\       每个测试开头都 栈清空，跑出来的结果才可重复。

: 测-深度  ( -- )
  栈清空
  栈深度  0 assert=
  10 压栈  20 压栈
  栈深度  2 assert=
  看栈顶  20 assert=
  弹栈 drop
  栈深度  1 assert=
  栈清空
  assert-栈空 ;

\ ⚠ 坑：别超过 栈容量（这里是 100），否则测的是溢出不是求和。
: 测-来回  ( -- )
  栈清空
  100 0 do  i 压栈  loop
  栈深度  100 assert=
  0
  100 0 do  弹栈  +  loop
  4950 assert=                       \ 0+1+...+99
  栈空?  true assert=
  assert-栈空 ;

\ 浮点和双精度也得覆盖到，否则 assert≈ / assert-深 就白写了
: 测-浮点  ( -- )
  2.0e0 fsqrt        1.414213562e0  assert≈
  1.0e0 3.0e0 f/     0.333333333e0  assert≈
  0.0e0 fsin         0.0e0          assert≈
  assert-栈空 ;

: 测-双精度  ( -- )
  1234567890123.   1234567890123.  assert-深
  0.               0.              assert-深
  assert-栈空 ;

: 跑全部  ( -- )
  测-基本
  测-空栈弹出
  测-溢出
  测-深度
  测-来回
  测-浮点
  测-双精度
  .汇总 ;

跑全部

\ ============================================================
\  四、栈平衡的自动检查
\ ============================================================
cr cr .( ---- 栈平衡检查 ----) cr

\ ⚠ 坑：被测词要是抛了异常而外面没 catch，gforth 会退回交互态
\       等着读 stdin —— 表现就是脚本"卡死"不动，而不是报错退出。
\       所以要么保证被测词不会抛，要么外面套一层 catch。
\       跑自动化脚本时，末尾一定要写 bye。

\ Forth 最常见的 bug 就是栈不平衡。
\ 用一个包装词，在调用前后比对深度，能自动抓出来。

\ 思路很简单：先记深度 -> 跑被测词 -> 再记深度 -> 比对差值 -> 把吐出来的东西清掉
\
\ ⚠ 坑：差值 = 调用后深度 - 调用前深度。
\       压栈 吃掉 1 个、不吐，所以是 -1；弹栈 吐 1 个，所以是 +1。
\ ⚠ 坑：被测词吐出来的结果会留在栈上，测完要 drop 干净，
\       否则一个测试跑完，后面的测试全被污染。

0 value 进入深度
0 value 实际差

\ ⚠ 坑：这里千万别写 `depth 进入深度 ?do drop loop`。
\       ?DO 只在「起点 = 上限」时跳过；起点 > 上限 不是"不循环"，
\       而是用无符号比较一路加到回绕 —— 约 2^64 次，表现就是死循环。
\       被测词吃掉的数比吐出的多时（比如 压栈），正好踩中这个情况。
\       要"可能 0 次"的清理，用 begin while repeat 最稳：
: 检查差值  { xt 期望差 -- }
  depth to 进入深度
  xt execute
  depth 进入深度 -  to 实际差
  begin  depth 进入深度 >  while  drop  repeat   \ 清掉被测词留下的结果
  实际差 期望差 =
  if   记通过
  else 记失败
       cr ."    " .红 ." 期望深度变化 " 期望差 . ."  实际 " 实际差 .
  then ;

\ ⚠ 坑：别在冒号定义里写 :noname 来造被测词 —— 嵌套定义很容易和
\       外层定义的 locals / 返回栈打架。老老实实起个名字更稳。
: 试-压栈  ( n -- )   压栈 ;
: 试-弹栈  ( -- n )   弹栈 ;
: 试-看顶  ( -- n )   看栈顶 ;
: 试-清空  ( -- )     栈清空 ;

: balance-demo  ( -- )
  栈清空  1 压栈  2 压栈          \ 先垫两个数，免得弹栈/看栈顶抛下溢
  cr ." 压栈  ( n -- )  ："
  42  ['] 试-压栈  -1  检查差值
  cr ." 弹栈  ( -- n )  ："
      ['] 试-弹栈   1  检查差值
  cr ." 看栈顶 ( -- n ) ："
      ['] 试-看顶   1  检查差值
  cr ." 栈清空 ( -- )   ："
      ['] 试-清空   0  检查差值
  cr ." 故意把期望值写错，看它怎么报："
  42  ['] 试-压栈   1  检查差值
  .汇总 ;

balance-demo

\ ============================================================
\  五、性能基准
\ ============================================================
cr cr .( ---- 基准 ----) cr

\ utime ( -- d微秒 ) 双精度，直接做 d- 最省事
\ ⚠ 坑：取低 32 位来相减是不行的 —— 微秒计数跨过 2^32 就翻车了。
\       老老实实用双精度：utime 2>r ... utime 2r> d- d>s
: 计时  ( xt -- 微秒 )
  utime 2>r
  execute
  utime 2r> d- d>s ;

: 微秒.  ( n -- )
  dup 1000 <
  if    . ." 微秒"
  else  1000 /  dup 1000 <
        if   . ." 毫秒"
        else 1000 / . ." 秒"
        then
  then ;

\ recurse = 递归调用当前正在定义的这个词
\ ⚠ 坑：gforth 里冒号定义的名字要等 ; 之后才可见，
\       所以在定义体里直接写自己的名字会 Undefined word，必须用 recurse。
: 朴素斐波那契  ( n -- n )
  dup 2 <  if  exit  then
  dup 1- recurse  swap 2 - recurse  + ;

\ ⚠ 坑：nip 留栈顶、drop 留次栈顶，别搞反。
\       这个循环结束时栈是 ( fib(n) fib(n-1) )，
\       栈顶是 fib(n-1)，要的是下面那个，所以是 drop 不是 nip。
: 迭代斐波那契  { n -- n }
  0 1  n 0 ?do  over + swap  loop  drop ;

\ ⚠ 坑：['] 是编译期查词，只能在冒号定义里面用；
\       顶层要拿 xt 得写 ' 名字（但那个也不能用在定义里）。
: 跑朴素  ( -- )  25 朴素斐波那契 drop ;
: 跑迭代  ( -- )  25 迭代斐波那契 drop ;

: bench-demo  ( -- )
  cr ." fib(25) = " 25 朴素斐波那契 .
  cr ." 朴素递归耗时："
  ['] 跑朴素 计时  微秒.
  cr ." 迭代    耗时："
  ['] 跑迭代 计时  微秒.
  cr ." 两种算法结果一致："
  25 朴素斐波那契  25 迭代斐波那契  assert= ;

bench-demo

\ ============================================================
\  六、标准库 tester.fs（放最后是有原因的）
\ ============================================================
cr cr .( ---- 标准 tester.fs ----) cr

\ gforth 自带 John Hayes 的 tester，语法是
\   T{ 输入 -> 期望输出 }T
\ 只测整数/栈效果时很方便。但在这台机器的 0.7.3 上，加载它有三个坑：
\
\ ⚠ 坑 1：tester.fs 里有一行 `: { T{ ;` —— 它把 `{` 抢去当 T{ 的别名了。
\         加载之后 `{ a b }` 这种 locals 语法就废了，再写就是 Undefined word。
\         所以这一节必须放在所有用 locals 的定义**之后**。
\ ⚠ 坑 2：加载它会把 BASE 切成 16 进制，之后要自己 decimal。
\ ⚠ 坑 3：加载时会在 stderr 打一行 "redefined {"。
\         想让脚本输出干净，加载前先 warnings off。
\ ⚠ 坑 4：T{ }T 是给**顶层解释态**用的，别塞进冒号定义里 ——
\         里面的数字会被编译成字面量，测的就不是你想要的东西了。
\ ⚠ 坑 5：浮点测试（R{ }T / X{ }T）在这台机器上报错，
\         浮点请用上面自制的 assert≈。

warnings off
require test/tester.fs
decimal

cr ." 用 T{ }T 写（没报错就是全过了，失败会打印 INCORRECT RESULT）："
cr T{ 1 2 + -> 3 }T
cr T{ 5 6 7 -> 5 6 7 }T
cr T{ -> }T
cr T{ 3 4 * 2 - -> 10 }T
cr T{ 1 2 3 rot -> 2 3 1 }T
cr T{ -1 dup * -> 1 }T
cr T{ 0 dup -> 0 0 }T
cr ." （上面如果全是空行，说明全过了）"

