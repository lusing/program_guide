: summary  ( -- )
  cr ." 1. 每个测试开头重置状态，测试之间不要互相依赖"
  cr ." 2. 每个测试结尾都 assert-栈空 —— 能抓住九成的 Forth bug"
  cr ." 3. 异常路径也要测（用 assert-抛出）"
  cr ." 4. 浮点别用 = ，也别用 f~ ，自己算 |差| < 容差"
  cr ." 5. 断言词自己也要保证栈平衡，否则测试会骗你"
  cr ." 6. 基准测试要跑双精度计时，别只取 utime 低 32 位" ;

