\ ============================================================
\  八、实战：复利计算器
\ ============================================================
cr cr .( ---- 复利 ----) cr

\ 复利公式： A = P × (1 + r/n)^(n×t)
: compound  { f: p f: r f: n f: t -- f: a }
  p  1.0e0 r n f/ f+  n t f*  f**  f* ;

: compound-demo  ( -- )
  cr ." 本金 10000，年利率 4.5%，按年复利，存 10 年："
  cr ."   到期 = " 10000.0e0 0.045e0 1.0e0 10.0e0 compound f.
  cr ." 同样条件，按月复利（n=12）："
  cr ."   到期 = " 10000.0e0 0.045e0 12.0e0 10.0e0 compound f.
  cr ." 按月复利多出来的钱 = "
     10000.0e0 0.045e0 12.0e0 10.0e0 compound
     10000.0e0 0.045e0  1.0e0 10.0e0 compound  f-  f. ;
compound-demo

\ ============================================================
\  九、实战：数值积分（梯形法）
\ ============================================================
cr cr .( ---- 数值积分 ----) cr

\ 用梯形法求 ∫f(x)dx 从 a 到 b，分 n 段
\ xt 是被积函数 ( r -- r )
: integrate  { f: a f: b xt n -- }
  0.0e0
  n 0 do
    a  b a f-  i s>f f*  n s>f f/  f+   xt execute   \ f(x_i)
    a  b a f-  i 1+ s>f f*  n s>f f/  f+  xt execute  \ f(x_{i+1})
    f+  2.0e0 f/
    b a f-  n s>f f/  f*
    f+
  loop ;

\ ⚠ 坑：`f:` 这种类型前缀只能写在 { } 里面，
\       `:noname f: ( ... )` 是不合法的。
:noname  ( f: x -- x^2 )  fdup f* ;  constant 'square
:noname  ( f: x -- sin x )  fsin ;   constant 'sin

: int-demo  ( -- )
  cr ." ∫x² dx  从 0 到 1   = " 0.0e0 1.0e0 'square 1000 integrate f. ."   (理论值 0.3333)"
  cr ." ∫sin x dx 从 0 到 π = " 0.0e0 pi 'sin 1000 integrate f.           ."   (理论值 2.0)" ;
int-demo

\ ============================================================
\  十、实战：牛顿迭代求平方根
\ ============================================================
cr cr .( ---- 牛顿法 ----) cr

\ ⚠ 坑（血泪教训）：f~ 会一次性吃掉【三个】浮点数
\   （ r1 r2 容差 -- flag ），所以别想当然地写
\   `fover fover f- fabs 1.0e-12 f~` 去比较栈顶两个值 —— 那会把
\   两个值连同容差一起吃掉，循环里就再也拿不回来了（表现为死循环）。
\   老老实实用变量存中间结果，最省心。
fvariable g-cur
fvariable g-new

: newton-sqrt  { f: x -- f: r }
  x  f0<  abort" 负数没有实数平方根"
  x  f0=  if  0.0e0  exit  then
  x g-cur f!                                   \ 初始猜测 = x 自己
  begin
    \ 牛顿迭代： g' = (g + x/g) / 2
    g-cur f@  x g-cur f@ f/  f+  2.0e0 f/  g-new f!
    \ 收敛判据：两次猜测够接近了吗（f~ 自己会算差值并比对容差）
    g-cur f@  g-new f@  1.0e-12 f~
    g-new f@ g-cur f!                          \ 迭代
  until
  g-cur f@ ;

: newton-demo  ( -- )
  cr ." √2  (牛顿法) = " 2.0e0   newton-sqrt f.
  cr ." √2  (内置)   = " 2.0e0   fsqrt f.
  cr ." √10 (牛顿法) = " 10.0e0  newton-sqrt f.
  cr ." √10 (内置)   = " 10.0e0  fsqrt f. ;
newton-demo

