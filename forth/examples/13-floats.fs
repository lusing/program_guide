cr cr .( ---- 变量 ----) cr

\   fconstant  创建浮点常量
\   fvariable  创建浮点变量（初值是 0，不是你写的那个数！）
\ ⚠ 坑：gforth 0.7.3 没有 fvalue / fto，别写 `1.0e0 fvalue x`
\ ⚠ 坑：fvariable 的初值【永远是 0】，`1.5e0 fvariable v` 里
