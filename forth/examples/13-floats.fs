#! /usr/bin/env gforth
\ ============================================================
\  13-floats.fs —— 浮点数
\  运行： gforth examples/13-floats.fs
\ ============================================================

\ Forth 有三套独立的栈：数据栈(整数)、浮点栈、返回栈。
\ 浮点运算全部在浮点栈上进行，所以写法和整数那套完全不同。

cr .( ==== 13  浮点数 ====) cr

\ ============================================================
\  一、浮点字面量怎么写（最容易踩的坑）
\ ============================================================
cr .( ---- 字面量 ----) cr

\ ⚠ 坑 1：没有 f" ..." 这种写法！必须写成 数字 + e + 指数
\         3.5e0      = 3.5 × 10^0
\         1.0e-3     = 0.001
\         6.022e23   = 6.022 × 10^23
\ ⚠ 坑 2：光写 1.0e 或 2.5e 不行，e 后面必须有指数（哪怕是 e0）
\ ⚠ 坑 3：光写 3.14（不带 e）会被当成【双精度整数】，不是浮点！

cr .( 3.5e0 = ) 3.5e0 f.
cr .( 1.0e-3 = ) 1.0e-3 f.
cr .( 6.022e23 = ) 6.022e23 f.
cr .( 对比：3.14 不带 e，是双精度整数 ) 3.14 d.

\ ============================================================
\  二、四则运算
\ ============================================================
cr cr .( ---- 四则运算 ----) cr

\   f+  f-  f*  f/      —— 都是 ( r1 r2 -- r )
\   fnegate  fabs       —— ( r -- r )
\   fmin  fmax          —— ( r1 r2 -- r )
\   fsqrt  fexp  fln  flog  f**
\   fsin  fcos  ftan  fasin  facos  fatan  fatan2
\   f2*  f2/            —— 乘以/除以 2，比 f* 快

: arith-demo  ( -- )
  cr ." 1.5 + 2.25  = " 1.5e0 2.25e0 f+ f.
  cr ." 7.5 - 9.0   = " 7.5e0 9.0e0 f- f.
  cr ." 1.2 × 3.0   = " 1.2e0 3.0e0 f* f.
  cr ." 1.0 ÷ 3.0   = " 1.0e0 3.0e0 f/ f.
  cr ." -(-2.5)     = " -2.5e0 fnegate f.
  cr ." |-3.7|      = " -3.7e0 fabs f.
  cr ." min(3,5)    = " 3.0e0 5.0e0 fmin f.
  cr ." max(3,5)    = " 3.0e0 5.0e0 fmax f.
  cr ." √2          = " 2.0e0 fsqrt f.
  cr ." 2^10        = " 2.0e0 10.0e0 f** f.
  cr ." e^1         = " 1.0e0 fexp f.
  cr ." ln(10)      = " 10.0e0 fln f.
  cr ." log10(100)  = " 100.0e0 flog f.
  cr ." sin(π/6)    = " pi 6.0e0 f/ fsin f.
  cr ." atan2(1,1)  = " 1.0e0 1.0e0 fatan2 f. ."  (= π/4)" ;
arith-demo

\ ============================================================
\  三、浮点栈的搬运工
\ ============================================================
cr cr .( ---- 栈操作 ----) cr

\   fdup  fdrop  fswap  fover  frot  fnip  ftuck
\   ⚠ 坑：整数那套 dup/swap/over 对浮点栈【无效】，必须加 f 前缀

: stack-demo  ( -- )
  cr ." fdup:  " 1.0e0 fdup f. f.
  cr ." fswap: " 1.0e0 2.0e0 fswap f. f.
  cr ." fover: " 1.0e0 2.0e0 fover f. f. f.
  cr ." frot:  " 1.0e0 2.0e0 3.0e0 frot f. f. f. ;
stack-demo

\ ============================================================
\  四、比较：千万别用 =
\ ============================================================
cr cr .( ---- 比较 ----) cr

\   f<  f>  f<=  f>=  f0<  f0=  f0>  f=
\ ⚠ 坑：gforth 确实有 f=，但它做的是【精确比较】，
\       对算出来的浮点数几乎永远返回假。真正判等要用 f~。

\   f~ ( f: r1 r2 r3 -- ) ( -- flag ) 是"近似相等"，但有个大坑（见下）
\ ⚠ 坑：gforth 0.7.3 上的 f~ 用负容差（r3 < 0，ANS 说是绝对误差比较）
\       时行为反直觉，实测：
\         f: 0.0e0 0.0e0 -1.0e-9  f~   ->  false  ← 0 和 0 都不相等！
\         f: 0.0e0 1.0e-12 -1.0e-9 f~  ->  false  ← 明明在 1e-9 以内
\         f: 1.0e0 1.0e0 -1.0e-9   f~  ->  true
\       也就是它更接近"相对误差"，在 0 附近完全不能用。
\       所以：正容差（相对）能用；想做绝对误差判等，自己写
\         f: a b --  f- fabs 1.0e-9 f<
: f≈  ( f: a b -- )  ( -- flag )    f- fabs  1.0e-9 f< ;

: cmp-demo  ( -- )
  cr ." 1.0 < 2.0 ? "  1.0e0 2.0e0 f< .
  cr ." 0.1+0.2 == 0.3 ? "  0.1e0 0.2e0 f+  0.3e0  f=  if ." 相等" else ." 不相等" then
  cr ."    ↑ 这就是传说中的 0.30000000000000004"
  cr ." 用 f~ 判等（正容差 1e-9，相对）："
     0.1e0 0.2e0 f+  0.3e0  1.0e-9 f~  if ."   相等（在容差内）" else ."   不相等" then
  cr ." 1.0 vs 1.5，容差 1e-9："
     1.0e0 1.5e0 1.0e-9 f~  if ."   相等" else ."   不相等" then
  cr ." 自己写的 f≈ （绝对误差，0 附近也对）："
     0.0e0 0.0e0 f≈  if ."   0 和 0 相等" else ."   0 和 0 竟然不相等" then
     0.0e0 1.0e-12 f≈  if ."   0 和 1e-12 相等" else ."   不相等" then
     1.0e0 1.5e0 f≈  if ."   相等" else ."   1 和 1.5 不相等" then ;
cmp-demo

\ ============================================================
\  五、整数 ↔ 浮点转换
\ ============================================================
cr cr .( ---- 转换 ----) cr

\   s>f   ( n -- r )      单精度整数 → 浮点
\   d>f   ( d -- r )      双精度整数 → 浮点
\   f>s   ( r -- n )      浮点 → 整数（截断，不是四舍五入）
\   f>d   ( r -- d )      浮点 → 双精度整数
\   floor fround ftrunc   取整（结果仍是浮点）

: conv-demo  ( -- )
  cr ." s>f:  42   -> " 42 s>f f.
  cr ." d>f:  10亿  -> " 1000000000. d>f f.
  cr ." f>s:  3.99  -> " 3.99e0 f>s .
  cr ."   f>s 是截断不是四舍五入，想四舍五入就用 fround f>s"
  cr ." fround: 3.99 -> " 3.99e0 fround f>s .
  cr ." floor(2.7)  = " 2.7e0 floor f.
  cr ." floor(-2.7) = " -2.7e0 floor f. ."  （向下取整，注意负号）" ;
conv-demo

