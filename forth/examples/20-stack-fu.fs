\ ============================================================
\  二、书上例题：AX²+BX+C 的纯栈解法（霍纳式）
\ ============================================================
cr cr .( ---- 多项式：AX²+BX+C ----) cr

\ 《IBM-PC FORTH 语言》§1.2.1 的经典例题：AX²+BX+C 改写成
\   (AX+B)X + C，逆波兰序 A X * B + X * C +
\ 变量化输入 ( a b c x -- r )，5 个词解决问题：

: poly  ( a b c x -- r )
  >r          \ x 进返回栈避难（注意：>r r 必须在本词内配对）
  rot         \ ( b c a )
  r@ *        \ ( b c a*x )
  rot         \ ( c a*x b )
  +           \ ( c a*x+b )
  r> *        \ ( c (a*x+b)*x )
  + ;         \ ( (a*x+b)*x + c )  ← 就是 a*x²+b*x+c

2 3 4 5 poly . cr         \ 69（2*25+3*5+4）
1 -1 0 7 poly . cr        \ 42（x=7 时的 x²-x）

\ 对照：同样的式子用局部变量写，像「普通语言」但多了开销
: poly-locals  ( a b c x -- r )  { a b c x }  a x * b + x * c + ;
2 3 4 5 poly-locals . cr  \ 69，殊途同归

\ ============================================================
\  三、返回栈三定律（Thinking Forth 第 7 章）
\ ============================================================
cr cr .( ---- 返回栈三定律 ----) cr

\ 定律 1：>r ... r> 必须在同一个冒号定义内配对；
\         跨 if/loop 分界线借用是未定义行为。
\ 最实用的暂存模式：先把「待会儿还要用」的数藏进返回栈，
\ 让数据栈腾出手干别的：
: inner   ( n -- n*10 )  10 * ;
: combine ( a b -- a*10+b )   \ b 暂存进 R，加工完 a 再取回
  >r  inner  r>  + ;
3 4 combine . cr           \ 34

: avg3  ( a b c -- avg )  \ 暂存 c，先算 a+b
  >r + r@ + 3 / r> drop ;
10 20 30 avg3 . cr        \ 20

\ 定律 2：DO 循环的循环参数就住在返回栈上——I / J 是在偷看它
: inner-outer  ( -- )
  3 1 do                    \ 外层 j
    4 1 do                  \ 内层 i
      j 10 * i + 4 .r
    loop
  loop cr ;
inner-outer                 \ 11 12 13 21 22 23

\ 定律 3：双字组版 2>r / 2r@ / 2r>——双精度数暂存神器
: d+twice  ( d1 d2 -- d1+2*d2 )   \ d2 暂存进返回栈，取用两次再取出配对
  2>r  2r@ 2r@ d+  2r> 2drop  d+ ;
10. 30. d+twice d. cr      \ 70

\ ⚠ 坑（复习）：顶层跨行 >r ... r> 会 Invalid memory address，
\ 因为行与行之间返回栈上躺着解释器自己的返回地址。

