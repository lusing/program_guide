1 2 3 -rot   show    \ <3> 3 1 2   -rot：反向三旋（gforth 扩展）
1 2 3 4 2 roll show  \ <4> 1 3 4 2 roll：把第 2 项抽到顶（下标从 0 起）
1 2 3 2 pick show    \ <4> 1 2 3 1 pick：复制第 2 项到顶（下标从 0 起）
1 2 3 depth . cr drop drop drop

