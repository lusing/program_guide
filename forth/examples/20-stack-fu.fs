\ 版本 1（反面教材）长这样——2>r tuck swap rot @ + over * ...，
\ 一坨深栈戏法写完自己都读不懂。这里不真写，直接看下面两种正解：

\ 版本 2：纯栈版——rot 把「当前该乘权重的那个」转到栈顶
\ 记法：rot 把第 3 项转到顶；-rot 把顶转到第 3 项。
\ 本例实测教训：第 5 步写错方向（swap/-rot），因为加法交换律，
\ 结果 574 长得很像回事——栈戏法出错必须逐行 .s 验证！
: wavg  ( n1 n2 n3 -- avg )
  rot 30 *          \ ( n2 n3 n1*30 )
  rot 50 *          \ ( n3 n1*30 n2*50 )
  rot 20 *          \ ( n1*30 n2*50 n3*20 )
  + + 100 / ;
88 92 75 wavg . cr         \ 87（=87.4 截断；手工验算 2640+4600+1500）

\ 版本 3：局部变量版——三个数的关系一目了然
: wavg-locals  ( n1 n2 n3 -- avg )
  { 数学 英语 体育 }
  数学 30 *  英语 50 *  体育 20 *  + + 100 / ;
88 92 75 wavg-locals . cr  \ 87

\ Thinking Forth 的判据：如果一个词的栈注释你已经写不清楚，
\ 或者写出来像 ( a b c d -- c d a*b+c )，就该拆词或上局部变量。

