\ 反例（这段是无效代码，故意留着当反面教材，别照抄）：
\   : bad-style  { a b c d e -- r }
\     a b +  c d *  +  e -  abs  2 /  to r   \ 局部变量不能用 TO 赋值
\     r ;

\ 正解：把局部变量当成"只读的命名栈槽"
: ok-style  { a b c d e -- r }
  a b +  c d *  +  e -  abs  2 / ;

\ 正解：拆成三个短词，中间结果过栈
: sum2   ( x y -- s )   + ;
: prod2  ( x y -- p )   * ;
: good-style  ( a b c d e -- r )
  >r  2>r  sum2  2r>  prod2  +  r>  -  abs  2/ ;

: style-demo  ( -- )
  cr ." 两种写法结果一样："
  cr ."   一整个长词 = " 1 2 3 4 5 ok-style .
  cr ."   拆成短词   = " 1 2 3 4 5 good-style .
  cr ." 但好的 Forth 代码是一个个 3~5 行的短词，而不是一个 50 行的长词" ;
