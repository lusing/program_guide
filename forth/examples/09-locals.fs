\ ⚠ 局部变量不是"变量"，它只是有名字的栈槽，不能用 TO 赋值
\ 想当累加器，要么把中间值留在栈上，要么配一个 VALUE
0 value acc
: sum-by-value  { n -- sum }
  0 to acc
  n 1+ 1 ?do  i acc +  to acc  loop
  acc ;

: sum-by-stack  { n -- sum }
  0  n 1+ 1 ?do  i +  loop ;

: sum-demo  ( -- )
  cr ." 用 VALUE 当累加器：1+..+100 = " 100 sum-by-value .
  cr ." 中间值留在栈上：  1+..+100 = " 100 sum-by-stack . ;
