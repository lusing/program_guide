\  六、实战：解一元二次方程
\ ============================================================
cr cr .( ---- 解一元二次方程 ----) cr

: quadratic  { f: a  f: b  f: c -- }
  b b f*  4.0e0 a f* c f*  f-        \ 判别式 Δ，留在浮点栈上
  fdup f0<  if
    ." 无实数根（Δ = " f. ." ）"
  else
    ." Δ = " fdup f.
    fsqrt                         \ 浮点栈上现在只剩 √Δ
    cr ." x1 = " fdup  b fnegate f+  2.0e0 a f*  f/  f.
    cr ." x2 = "       b fnegate fswap f-  2.0e0 a f*  f/  f.
  then ;

: quad-demo  ( -- )
  cr ." x² - 5x + 6 = 0 ："
  1.0e0 -5.0e0 6.0e0 quadratic
  cr cr ." x² + 2x + 5 = 0 ："
  1.0e0 2.0e0 5.0e0 quadratic  cr ;
