\  五、局部变量 + 循环
\ ============================================================
cr cr .( ---- 局部变量与循环 ----) cr

: dot-product  { addr1 addr2 n -- s }   \ 点积
  0 { s }
  n 0 ?do
    addr1 i cells + @   addr2 i cells + @  *   s +  to s
  loop
  s ;

create v1  1 , 2 , 3 , 4 ,
create v2  10 , 20 , 30 , 40 ,

cr ." [1,2,3,4]·[10,20,30,40] = " v1 v2 4 dot-product .

