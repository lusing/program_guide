// 第 02 章配套程序：用固定文本陈述三条结论——
// 为什么精确的静态分析不可能存在，以及 sound / complete 的取舍。
#include <iostream>

int main() {
    using namespace std;

    cout << "结论一: 停机问题 -> '程序是否会在某输入上出错' 不可判定\n";
    cout << "  假设存在分析器 A, 对任意程序都能判定'它是否可能除零'。\n";
    cout << "  可以构造一个程序: 先让 A 分析它自己, 再刻意做出与答案相反的行为\n";
    cout << "  (A 说安全就除零, A 说会除零就正常返回) —— 于是 A 必错, 矛盾。\n\n";

    cout << "结论二: Rice 定理\n";
    cout << "  程序对'部分递归函数的非平凡语义性质'一律不可判定。\n";
    cout << "  推论: '总能输出正数''不存在内存泄漏'等性质, 都没有精确答案。\n\n";

    cout << "结论三: 只能做可靠 (sound) 的近似\n";
    cout << "  sound & complete (既不漏报也不误报): 不可能, 等价于精确判定\n";
    cout << "  sound (宁可误报, 不可漏报): 错误真发生时, 分析一定提前告警\n";
    cout << "  complete (宁可漏报, 不可误报): 不告警时保证没问题, 但可能漏掉真错误\n";
    cout << "  两者都不保证: 只能做启发式提示\n\n";

    cout << "精度 -- 成本谱系:\n";
    cout << "  越精确的近似, 需要区分越多程序状态, 计算与存储成本越高;\n";
    cout << "  静态分析的全部工程艺术性, 就是在这条谱系上选择落点。\n";

    cout << "[chapter 02 OK]\n";
    return 0;
}
