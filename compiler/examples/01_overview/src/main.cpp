// 第 1 章配套程序：用固定文本演示"同一程序，三种工具各自知道什么"
// 以及静态分析的四类典型应用。
#include <iostream>

int main() {
    using namespace std;

    cout << "被讨论的程序片段:\n";
    cout << "  x = input;        // 从输入流读一个整数\n";
    cout << "  output x / x;     // 输出 x 除以 x\n\n";

    cout << "== 编译器的视角 ==\n";
    cout << "  知道: 语法合法; 除法两侧类型都是 int; 可以生成可执行代码\n";
    cout << "  不知道: 运行时输入是否为 0 —— 若 x=0 则触发除零\n\n";

    cout << "== lint 风格规则检查器的视角 ==\n";
    cout << "  知道: 按预置规则匹配可疑模式 (硬编码常量除法、某些 API 误用)\n";
    cout << "  不知道: 本例两侧都是同一个变量, 规则库未必覆盖, 可能漏报\n\n";

    cout << "== 静态分析器的视角 ==\n";
    cout << "  知道: input 可能产生任意整数, 包括 0 (可靠近似)\n";
    cout << "        因而 x 的可能取值集合包含 0, 除法可能除零\n";
    cout << "  代价: 它也会把'事实上不会为 0'的情形报成可能 —— 可靠但不精确\n\n";

    cout << "静态分析的四类应用:\n";
    cout << "  1. 程序验证   证明程序满足性质 (如永远不会空指针解引用)\n";
    cout << "  2. 缺陷发现   在部署前找出除零、资源泄漏、缓冲区越界\n";
    cout << "  3. 编译优化   常量传播、死代码消除、寄存器分配都依赖分析\n";
    cout << "  4. 安全分析   信息流(污点)分析、恶意行为筛查\n";

    cout << "[chapter 01 OK]\n";
    return 0;
}
