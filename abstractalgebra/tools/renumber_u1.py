def main() -> None:
    import sys

    target = sys.argv[1] if len(sys.argv) > 1 else "docs"
    if target == "examples":
        files = []
        for sub in ("julia", "python", "prolog"):
            files += sorted((HERE.parent / "examples" / sub).glob("[0-9][0-9]_*.jl"))
            files += sorted((HERE.parent / "examples" / sub).glob("[0-9][0-9]_*.py"))
            files += sorted((HERE.parent / "examples" / sub).glob("[0-9][0-9]_*.pl"))
        files += sorted((HERE.parent / "examples" / "lean" / "Abstractalgebra").glob("*.lean"))
    else:
        files = sorted(DOCS.glob("*.md"))
    total = 0
    for f in files:
        src = f.read_text(encoding="utf-8")
        out = src
        cnt = 0

        def sub(m):
            nonlocal cnt
            key = (m.group(1), m.group(2))
            if key in M:
                cnt += 1
                k2, n2 = M[key]
                return k2 + " " + n2
            return m.group(0)

        out = PAT.sub(sub, out)
        if target == "docs" and f.name in HEADERS:
            old, new = HEADERS[f.name]
            if old in out:
                out = out.replace(old, new, 1)
                cnt += 1
            else:
                print("HEADER MISS:", f.name, old)
        if out != src:
            f.write_text(out, encoding="utf-8")
        print(f"{f.name}: {cnt} 处")
        total += cnt
    print("TOTAL", total)


if __name__ == "__main__":
    main()
